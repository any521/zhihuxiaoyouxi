/**
 * 读网格：把 level.ts 的网格按行打印成字符画，用来核对"哪格是墙 / 门 / 地板"。
 *
 * 为什么需要：截图只能看个大概，而且缩放/相机裁切会骗人（我踩过：以为南墙是地板）。
 * 网格是唯一的事实来源。
 *
 * 用法：node tools/读网格.mjs [行1] [行2]     # 默认打全部行
 *      node tools/读网格.mjs 20 29
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** 从 level.ts 里把中文常量抠出来（不用跑 TS，正则足够） */
const 源 = readFileSync(resolve('src/game/map/level.ts'), 'utf8');

const 瓦片表 = {};
{
  const 块 = /export const 瓦片 = \{([\s\S]*?)\} as const;/.exec(源)?.[1] ?? '';
  for (const m of 块.matchAll(/^\s*([\u4e00-\u9fa5A-Za-z]+):\s*(\d+)/gm)) 瓦片表[m[1]] = Number(m[2]);
}
const 布局 = {};
{
  const 块 = /const 布局 = \{([\s\S]*?)\} as const;/.exec(源)?.[1] ?? '';
  for (const m of 块.matchAll(/^\s*([\u4e00-\u9fa5A-Za-z]+):\s*(\d+)/gm)) 布局[m[1]] = Number(m[2]);
  for (const m of 块.matchAll(/^\s*([\u4e00-\u9fa5A-Za-z]+):\s*\[(\d+),\s*(\d+)\]/gm)) {
    布局[m[1]] = [Number(m[2]), Number(m[3])];
  }
}
const 地图宽 = Number(/export const 地图宽 = (\d+)/.exec(源)[1]);
const 地图高 = Number(/export const 地图高 = (\d+)/.exec(源)[1]);

const 名 = (号) => Object.keys(瓦片表).find((k) => 瓦片表[k] === 号) ?? String(号);
const 符号 = {
  白墙: '█',
  玻璃: '▒',
  门横左: '╪',
  门横右: '╪',
  门竖上: '╫',
  门竖下: '╫',
  门横左关: '×',
  门横右关: '×',
  门竖上关: '×',
  门竖下关: '×',
  浅灰地毯: '·',
  深灰地毯: ',',
  防滑砖: ':',
  抛光砖: '=',
  走廊地砖: '-',
  木地板: '~',
  桌面: 'T',
};

/**
 * 这里**不导入** level.ts（它是 TS，node 跑不了），而是把造网格的逻辑抄一遍。
 * ⚠️ 抄的时候必须和 level.ts 的 造网格() 一模一样，否则量出来的东西没意义。
 */
function 造网格() {
  const g = [];
  for (let y = 0; y < 地图高; y += 1) g.push(new Array(地图宽).fill(瓦片表.白墙));
  const 铺 = (x1, y1, x2, y2, t) => {
    for (let y = Math.max(0, y1); y <= Math.min(地图高 - 1, y2); y += 1) {
      for (let x = Math.max(0, x1); x <= Math.min(地图宽 - 1, x2); x += 1) g[y][x] = t;
    }
  };
  const 竖墙 = (x, y1, y2, t = 瓦片表.白墙) => 铺(x, y1, x, y2, t);

  // ⚠️ 这一段必须和 level.ts 保持一致
  const 原始铺 = /铺\(布局\.外墙,[\s\S]*?瓦片\.抛光砖\);/.exec(源)[0];
  const 前台宽 = /铺\(布局\.外墙, 布局\.前台顶, ([^,]+), 布局\.前台底, 瓦片\.抛光砖\);/.exec(源)[1];
  console.log(`# level.ts 里前台那行是：铺(布局.外墙, 布局.前台顶, ${前台宽}, 布局.前台底, 抛光砖)`);
  console.log(`# 地图宽 ${地图宽}，外墙 ${布局.外墙} → 内宽应该是 x${布局.外墙}..${地图宽 - 布局.外墙 - 1}\n`);

  铺(布局.外墙, 布局.前台顶, 地图宽 - 布局.外墙 - 1, 布局.前台底, 瓦片表.抛光砖);
  铺(布局.外墙, 布局.主走廊顶, 地图宽 - 布局.外墙 - 1, 布局.主走廊底, 瓦片表.走廊地砖);
  铺(布局.竖廊西, 布局.南区北墙, 布局.竖廊东, 布局.前台顶 - 1, 瓦片表.走廊地砖);
  铺(布局.会议室A[0], 布局.北区顶, 布局.会议室A[1], 布局.北区底, 瓦片表.木地板);
  铺(布局.开放办公区[0], 布局.北区顶, 布局.开放办公区[1], 布局.北区底, 瓦片表.浅灰地毯);
  铺(布局.会议室B[0], 布局.北区顶, 布局.会议室B[1], 布局.北区底, 瓦片表.木地板);
  竖墙(布局.隔断西, 布局.北区顶, 布局.北区南墙, 瓦片表.玻璃);
  竖墙(布局.隔断东, 布局.北区顶, 布局.北区南墙, 瓦片表.玻璃);
  铺(布局.开放办公区[0], 布局.北区南墙, 布局.开放办公区[1], 布局.北区南墙, 瓦片表.玻璃);
  铺(布局.茶水间[0], 布局.南区顶, 布局.茶水间[1], 布局.南区底, 瓦片表.防滑砖);
  铺(布局.文印区[0], 布局.南区顶, 布局.文印区[1], 布局.南区底, 瓦片表.防滑砖);
  铺(布局.总监办公室[0], 布局.南区顶, 布局.总监办公室[1], 布局.南区底, 瓦片表.深灰地毯);
  铺(布局.储藏间[0], 布局.南区顶, 布局.储藏间[1], 布局.南区底, 瓦片表.防滑砖);
  竖墙(布局.茶水间[1] + 1, 布局.南区顶, 布局.南区底);
  竖墙(布局.文印区[1] + 1, 布局.南区顶, 布局.南区底);
  竖墙(布局.总监办公室[0] - 1, 布局.南区顶, 布局.南区底);
  竖墙(布局.储藏间[0] - 1, 布局.南区顶, 布局.南区底);

  // ⚠️ 顺序必须和 level.ts 一致：外墙 → 竖廊 → 开门（门的顺序反了正门会被外墙盖掉）
  for (let y = 0; y < 地图高; y += 1) {
    for (let x = 0; x < 地图宽; x += 1) {
      const 外 = y < 布局.外墙 || y >= 地图高 - 布局.外墙 || x < 布局.外墙 || x >= 地图宽 - 布局.外墙;
      if (外) g[y][x] = 瓦片表.白墙;
    }
  }
  铺(布局.竖廊西, 布局.南区北墙, 布局.竖廊东, 布局.前台顶 - 1, 瓦片表.走廊地砖);

  // ⚠️ 列可能写成 "布局.竖廊西 + 1"，所以正则要容得下空格和加号
  const 门表 = [...源.matchAll(/\[布局\.(北区南墙|南区北墙|南区南墙|正门行),\s*(布局\.[\u4e00-\u9fa5]+(?:\s*\+\s*\d+)?|\d+),\s*瓦片\.门横左\]/g)].map(
    (m) => {
      const 列式 = m[2];
      if (!列式.startsWith('布局')) return [布局[m[1]], Number(列式)];
      const 名 = /布局\.([\u4e00-\u9fa5]+)/.exec(列式)[1];
      const 加 = /\+\s*(\d+)/.exec(列式);
      return [布局[m[1]], 布局[名] + (加 ? Number(加[1]) : 0)];
    },
  );
  for (const [行, 列] of 门表) {
    g[行][列] = 瓦片表.门横左;
    g[行][列 + 1] = 瓦片表.门横右;
    if (行 >= 地图高 - 布局.外墙) {
      for (let y = 行 + 1; y < 地图高; y += 1) {
        g[y][列] = 瓦片表.门横左;
        g[y][列 + 1] = 瓦片表.门横右;
      }
    }
  }
  return g;
}

const g = 造网格();
const 行1 = Number(process.argv[2] ?? 0);
const 行2 = Number(process.argv[3] ?? 地图高 - 1);

// 列标尺
let 标 = '     ';
for (let x = 0; x < 地图宽; x += 1) 标 += x % 10 === 0 ? String((x / 10) % 10) : ' ';
console.log(标);
标 = '     ';
for (let x = 0; x < 地图宽; x += 1) 标 += String(x % 10);
console.log(标);

for (let y = 行1; y <= 行2; y += 1) {
  const 行 = g[y].map((号) => 符号[名(号)] ?? '?').join('');
  console.log(String(y).padStart(4) + ' ' + 行);
}

// 中轴对称检查：左右是不是镜像
console.log('\n中轴对称检查（x 与 44-x 是否同类；只关心墙/门/地板大类）：');
const 大类 = (号) => {
  const n = 名(号);
  if (n.includes('门')) return '门';
  if (n === '白墙') return '墙';
  if (n === '玻璃') return '玻璃';
  return '地';
};
let 不齐 = 0;
for (let y = 0; y < 地图高; y += 1) {
  for (let x = 0; x < 22; x += 1) {
    const a = 大类(g[y][x]);
    const b = 大类(g[y][地图宽 - 1 - x]);
    if (a !== b) {
      不齐 += 1;
      if (不齐 <= 24) console.log(`  行${y} x${x}(${a}) ↔ x${地图宽 - 1 - x}(${b})`);
    }
  }
}
console.log(不齐 ? `共 ${不齐} 处不对称` : '完全对称 ✓');
