/**
 * 移动端的虚拟输入（**摇杆 + 动作键**）。
 *
 * ⚠️ 为什么要有这个文件：小游戏/地图原来**只读键盘**（`this.keyA.isDown` 之类），
 *    手机上进来**一步都走不动**（用户问"移动端怎么移动和操作"时的实际状态）。
 *
 * 设计：DOM 那层（React）负责画摇杆和按钮、把状态写进这个模块；
 *       Phaser 那层**每帧读一次**，和键盘走**同一条路** —— 这样两套输入不会各写一份移动逻辑。
 *       所以这里是个**模块级的可变对象**，不是 React state（每帧 setState 会炸性能）。
 */

export type 动作名 = 'E' | '空格' | 'Q';

export const 虚拟输入 = {
  /** 摇杆方向，范围 -1..1；没按就是 0 */
  x: 0,
  y: 0,
  /** 本帧要执行的动作（**读一次就清空**，不会重复触发） */
  动作: [] as 动作名[],
  /** 这一帧有没有人在用触摸（用来决定要不要压住键盘） */
  在用: false,
};

/** DOM 那边每帧（或每次 pointermove）调，写入摇杆方向 */
export function 设摇杆(x: number, y: number): void {
  虚拟输入.x = x;
  虚拟输入.y = y;
  虚拟输入.在用 = x !== 0 || y !== 0;
}

export function 松摇杆(): void {
  虚拟输入.x = 0;
  虚拟输入.y = 0;
  虚拟输入.在用 = false;
}

/** DOM 的按钮按下时调（等价于敲一下键盘） */
export function 按动作(名: 动作名): void {
  虚拟输入.动作.push(名);
}

/** 场景每帧取走这一帧的动作（取完即清） */
export function 取动作(): 动作名[] {
  if (!虚拟输入.动作.length) return [];
  const 出 = [...虚拟输入.动作];
  虚拟输入.动作.length = 0;
  return 出;
}
