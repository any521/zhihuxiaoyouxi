/** 生成瓦片网格 */
function 造网格(): number[][] {
  const g: number[][] = [];
  for (let y = 0; y < 地图高; y += 1) g.push(new Array<number>(地图宽).fill(瓦片.白墙));

  const 铺 = (x1: number, y1: number, x2: number, y2: number, t: number): void => {
    for (let y = Math.max(0, y1); y <= Math.min(地图高 - 1, y2); y += 1) {
      for (let x = Math.max(0, x1); x <= Math.min(地图宽 - 1, x2); x += 1) g[y][x] = t;
    }
  };
  // ⚠️ t 必须显式标 number：不标会被推断成字面量类型，后面传别的瓦片号就报错
  const 竖墙 = (x: number, y1: number, y2: number, t: number = 瓦片.白墙): void =>
    铺(x, y1, x, y2, t);

  /* 前台接待区（抛光砖） */
  铺(布局.外墙, 布局.前台顶, 地图宽 - 布局.外墙 - 1, 布局.前台底, 瓦片.抛光砖);

  /* 主走廊（横向贯通） */
  铺(布局.外墙, 布局.主走廊顶, 地图宽 - 布局.外墙 - 1, 布局.主走廊底, 瓦片.走廊地砖);

  /* 竖向走廊：把前台和主走廊连起来 */
  铺(布局.竖廊西, 布局.南区北墙, 布局.竖廊东, 布局.前台顶 - 1, 瓦片.走廊地砖);

  /* 北区三个房间 */
  铺(布局.会议室A[0], 布局.北区顶, 布局.会议室A[1], 布局.北区底, 瓦片.木地板);
  铺(布局.开放办公区[0], 布局.北区顶, 布局.开放办公区[1], 布局.北区底, 瓦片.浅灰地毯);
  铺(布局.会议室B[0], 布局.北区顶, 布局.会议室B[1], 布局.北区底, 瓦片.木地板);
  // 会议室两侧玻璃隔断；开放办公区朝走廊的一面也是玻璃（通透）
  竖墙(布局.隔断西, 布局.北区顶, 布局.北区南墙, 瓦片.玻璃);
  竖墙(布局.隔断东, 布局.北区顶, 布局.北区南墙, 瓦片.玻璃);
  铺(布局.开放办公区[0], 布局.北区南墙, 布局.开放办公区[1], 布局.北区南墙, 瓦片.玻璃);

  /* 南区四个房间 */
  铺(布局.茶水间[0], 布局.南区顶, 布局.茶水间[1], 布局.南区底, 瓦片.防滑砖);
  铺(布局.文印区[0], 布局.南区顶, 布局.文印区[1], 布局.南区底, 瓦片.防滑砖);
  铺(布局.总监办公室[0], 布局.南区顶, 布局.总监办公室[1], 布局.南区底, 瓦片.深灰地毯);
  铺(布局.储藏间[0], 布局.南区顶, 布局.储藏间[1], 布局.南区底, 瓦片.防滑砖);
  竖墙(布局.茶水间[1] + 1, 布局.南区顶, 布局.南区底);
  竖墙(布局.文印区[1] + 1, 布局.南区顶, 布局.南区底);
  竖墙(布局.总监办公室[0] - 1, 布局.南区顶, 布局.南区底);
  竖墙(布局.储藏间[0] - 1, 布局.南区顶, 布局.南区底);

  /* 开门（门洞直接盖在墙上） */
  for (const [行, 列, 宽, t] of 门表) {
    for (let i = 0; i < 宽; i += 1) g[行][列 + i] = t;
  }

  /* 外墙最后铺，保证最外两圈一定是墙 */
  for (let y = 0; y < 地图高; y += 1) {
    for (let x = 0; x < 地图宽; x += 1) {
      const 外 =
        y < 布局.外墙 || y >= 地图高 - 布局.外墙 || x < 布局.外墙 || x >= 地图宽 - 布局.外墙;
      if (外) g[y][x] = 瓦片.白墙;
    }
  }
  g[布局.正门行][布局.竖廊西] = 瓦片.门横;
  g[布局.正门行][布局.竖廊东] = 瓦片.门横;

  return g;
}

export const 网格 = 造网格();

