const 开关键 = 'lks-audio-on';
const 池大小 = 3;

/** 每个音效维护一个小池子，轮着用，避免连发时被截断 */
const 池 = new Map<音效, HTMLAudioElement[]>();
let 轮转 = 0;

function 取元素(名: 音效): HTMLAudioElement | null {
  let 组 = 池.get(名);
  if (!组) {
    组 = [];
    for (let i = 0; i < 池大小; i += 1) {
      const a = new Audio(素材(文件名[名]));
      a.preload = 'auto';
      组.push(a);
    }
    池.set(名, 组);
  }
  const a = 组[轮转 % 池大小];
  轮转 += 1;
  return a ?? null;
}

/** 是否开着声音（默认开） */
export function 有声(): boolean {
  return window.localStorage.getItem(开关键) !== '0';
}

/**
 * 开/关声音。
 * ⚠️ **BGM 也要跟着走**：关静音只关音效、BGM 还在放的话，
 *    玩家会以为开关坏了（反过来也一样）。
 */
export function 设声音(开: boolean): void {
  window.localStorage.setItem(开关键, 开 ? '1' : '0');
  if (!开) {
    停BGM();
    return;
  }
  // 开回来：如果之前有曲子在放，重新起一遍（`停BGM` 会把 当前曲 清掉，所以这里没法恢复）
  // ⚠️ 具体放哪首由各个屏幕自己决定（它们会在下一帧重新调 `播BGM`）
}

/**
 * 播一个音效。
 * @param 名 - 音效键名
 * @param 音量 - 可选，覆盖默认音量
 */
export function 播放(名: 音效, 音量?: number): void {
  if (!有声()) return;
  const el = 取元素(名);
  if (!el) return;
  try {
    el.pause();
    el.currentTime = 0;
    el.volume = 音量 ?? 默认音量[名];
    // 浏览器可能因为"还没有用户交互"而拒绝，这是正常的，静默忽略
    void el.play().catch(() => {});
  } catch {
    /* 忽略 */
  }
}

/* ───────── 背景音乐 ───────── */

/** BGM 曲目（和 public/audio/bgm/bgm_<名>.wav 一一对应） */
export type 曲目 = '办公室' | '工作关' | '会议室';

let 当前曲: 曲目 | null = null;
/** 每首一个元素，切回来不用重新下载 */
const 曲池 = new Map<曲目, HTMLAudioElement>();

/** BGM 默认音量（比音效轻：它是垫底的，不能盖过音效和台词） */
const 曲音量: Record<曲目, number> = {
  办公室: 0.26,
  工作关: 0.3,
  会议室: 0.24,
};

/**
 * 换背景音乐。**同一首重复调用不会重头播**（否则每帧调一次就废了）。
 *
 * ⚠️ 用 `HTMLAudioElement + loop` 而不是 WebAudio：和音效共用一套机制，
 *    静音开关（`有声()`）只要判一处，不用维护两套。
 */
export function 播BGM(曲: 曲目): void {
  if (当前曲 === 曲) return;
  停BGM();
  当前曲 = 曲;
  if (!有声()) return;
  let el = 曲池.get(曲);
  if (!el) {
    el = new Audio(new URL(`audio/bgm/bgm_${曲}.wav`, document.baseURI).href);
    el.loop = true;
    el.preload = 'auto';
    曲池.set(曲, el);
  }
  el.volume = 曲音量[曲];
  // 浏览器在"还没有用户交互"时会拒绝播放，静默忽略（和音效一样的处理）
  void el.play().catch(() => {});
}

/** 停掉当前 BGM */
export function 停BGM(): void {
  for (const el of 曲池.values()) el.pause();
  当前曲 = null;
}

/** 现在在放哪一首（`null` = 没在放）—— 也给体检脚本用 */
export function 当前BGM(): 曲目 | null {
  return 当前曲;
}

