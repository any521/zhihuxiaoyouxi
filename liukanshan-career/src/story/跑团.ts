/**
 * 跑团式的「不偏离剧情的随机对话」。
 *
 * 用户问：「如果后续剧情会出现类似跑团的剧情，可以接入知乎 llm 模型来做不偏离剧情的随机对话」。
 *
 * 能。但关键在于**把"随机"关进笼子里** —— 这一层做的就是那个笼子：
 *
 *   引擎（本文件，纯逻辑、可离线单测）
 *     掷骰 → 判定 → 结果只有四种（大成功/成功/失败/大失败）
 *     每种结果**已经写好了确定性的后果**（指标、线索、台词、谁来说）
 *              ↓ 只把"结果"告诉 AI
 *   AI（llm.ts，可以没有 / 可以挂 / 可以超时）
 *     只负责把这一轮说得好看：一个镜头 + 一句对白
 *     不许新增事实：不许加人、不改结果、不提分数、不剧透
 *              ↓ 过闸（校验叙述 / 校验对白）
 *   兜底（作者的 后果.叙述 / 后果.对白）
 *     校验不过 / 超时 / 没配密钥 → 用作者预写好的那一句
 *
 * 所以**离线也一定是完整的一局**：AI 只是给同一局换一层皮。
 *
 * 铁律：AI 不得改分数、不得新增人物/线索、不得决定成败、不得编造知乎来源。
 *
 * ── 2026-09 增补：从「一句描写」升级成「一个镜头 + 一句对白」 ──
 * 用户要求：「跑团剧情增加知乎 AI 不偏离剧情的丰富有趣对话」。
 * 只写镜头描写不够"活"，所以每轮多给 AI 一句**台上人物的台词**：
 *   · **谁**能说话由作者写死（回合.在场）—— AI 不能凭空造人
 *   · 台词长度、禁词、越界人名、数值增减，全部和叙述走同一套闸
 *   · 兜底台词也由作者预写，AI 挂了就是作者那句
 * 于是"丰富有趣"来自 AI，"不偏离剧情"来自作者写死的在场名单 + 四档后果。
 */

/* ───────── 类型 ───────── */

/** 判定的结果档位。**只有这四种**，AI 无权新增 —— 这是"不偏离剧情"的根 */
export type 判定档 = '大成功' | '成功' | '失败' | '大失败';

/** 四种档位的固定顺序（UI 按这个顺序排，别依赖对象 key 顺序） */
export const 档位序: 判定档[] = ['大成功', '成功', '失败', '大失败'];

/** 一档后果：**作者写死**，AI 只描述、不改 */
export interface 后果 {
  /** 兜底镜头：AI 挂了 / 校验不过时用的那一句 */
  叙述: string;
  /** 兜底台词：这一轮在场某个人说的话（不写就是这一档没有台词） */
  对白?: string;
  /** 这一档由谁来说那句对白（不填就用 在场 的第一个人） */
  谁说?: string;
  信任?: number;
  协作?: number;
  成长?: number;
  /** 这一档能拿到的线索（**只有它进线索库**，AI 说的不算） */
  线索?: string;
}

/** 一回合的脚本：作者手写，AI 不许碰 */
export interface 回合 {
  /** 场景名（给 AI 的上下文用，例如「会议室 · 白板前」） */
  场景: string;
  /** 玩家这一轮要干的事（给 AI 的上下文用） */
  行动: string;
  /** 难度：掷骰 + 修正 ≥ 难度 才算成功 */
  难度: number;
  /**
   * 这一轮**在场的人**：AI 只准让这些人说话。
   *
   * 这是"不偏离剧情"最硬的一道锁 —— 名单由作者按剧情写死，
   * AI 编一个新人物出来会被 校验对白 挡下、退回作者的兜底台词。
   */
  在场: string[];
  /** 给 AI 的背景补充：这一轮到底在谈什么（可省） */
  谈的是?: string;
  /** **确定性后果**：每种档位写死"发生什么"。AI 只描述，不改这个。 */
  后果: Record<判定档, 后果>;
}

export interface 跑团配置 {
  id: string;
  /** 显示用的标题（例如「会议室 · 需求对齐」） */
  标题?: string;
  /** 这一段的目标（AI 的上下文，也是玩家的目标） */
  目标: string;
  /**
   * 给 AI 的**剧情上下文**：这一段戏的前因后果。
   * 写清楚它，AI 的话才会贴着剧情，而不是泛泛而谈。
   */
  背景: string;
  /** 回合上限（G5：15 轮上限） */
  上限: number;
  /** 命中多少次算通关（G5：第 4 章是 3 次） */
  通关命中: number;
  /** 连续失败多少次算翻车（G5） */
  翻车失败: number;
  回合: 回合[];
}

export interface 指标增量 {
  信任: number;
  协作: number;
  成长: number;
}

/** AI 或作者给出的"这一轮怎么说" */
export interface 描写 {
  叙述: string;
  对白?: string;
}

export interface 跑团结果 {
  档: 判定档;
  /** 这一轮的骰面（2d6 两颗） */
  骰子: [number, number];
  修正: number;
  合计: number;
  难度: number;
  /** 场景（回看时要用，AI 的叙述里不会重复它） */
  场景: string;
  /** 玩家这一轮做的事 */
  行动: string;
  /** 实际发出去的镜头（可能是 AI 的，也可能是兜底的） */
  叙述: string;
  /** 实际发出去的台词（没有就不显示） */
  对白?: string;
  /** 台词是谁说的 */
  谁说?: string;
  /** 这条叙述/对白从哪来 */
  来源: 'AI' | '兜底';
  /** 指标增量（**只来自脚本，与 AI 无关**） */
  指标: 指标增量;
  线索?: string;
}

export type 局况 = '进行中' | '通关' | '翻车' | '超时';

/* ───────── 掷骰与判定 ───────── */

/** 可注入的骰子（测试时换成固定序列，就能复现"连续大失败"这种边角）*/
export type 骰子 = () => number;
const 真骰子: 骰子 = () => 1 + Math.floor(Math.random() * 6);

/** 指标 → 掷骰修正：某一项越高越容易过（+0~+3） */
export function 修正值(指标: 指标增量): number {
  const 总 = 指标.信任 + 指标.协作 + 指标.成长;
  return Math.max(0, Math.min(3, Math.floor(总 / 9)));
}

/**
 * 判定。
 * 这里**只认骰子和难度**，不看 AI 说了什么 —— 顺序绝不能反。
 */
export function 判定(骰: [number, number], 修正: number, 难度: number): { 档: 判定档; 合计: number } {
  const 合计 = 骰[0] + 骰[1] + 修正;
  if (骰[0] === 6 && 骰[1] === 6) return { 档: '大成功', 合计 };
  if (骰[0] === 1 && 骰[1] === 1) return { 档: '大失败', 合计 };
  return { 档: 合计 >= 难度 ? '成功' : '失败', 合计 };
}

/* ───────── 一局的进度 ───────── */

export interface 局状态 {
  轮: number;
  命中: number;
  失误: number;
  指标: 指标增量;
  线索: string[];
  局况: 局况;
  /** 已经打过的叙述（回看用） */
  日志: 跑团结果[];
}

export function 开局(): 局状态 {
  return { 轮: 0, 命中: 0, 失误: 0, 指标: { 信任: 0, 协作: 0, 成长: 0 }, 线索: [], 局况: '进行中', 日志: [] };
}

/** 取这一轮该用的脚本（超过脚本长度就循环用最后一条，方便少写几条）*/
export function 取回合(配置: 跑团配置, 轮: number): 回合 {
  return 配置.回合[Math.min(轮, 配置.回合.length - 1)] as 回合;
}

/** 把 AI 的返回 / 一个字符串统一成 描写（内部用） */
function 归一(回: string | 描写 | null | undefined): 描写 | null {
  if (回 == null) return null;
  if (typeof 回 === 'string') return 回.trim() ? { 叙述: 回 } : null;
  if (typeof 回.叙述 !== 'string' || !回.叙述.trim()) return null;
  return 回;
}

/**
 * 打一轮。
 *
 * 这是一个**纯函数**：给定（局状态, 配置, 骰子）就能算出结果，
 * 不碰网络、不碰 AI。AI 的说法是**算完之后**再贴上去的（见 贴AI话）。
 * 这样"AI 挂了"永远只是少一层皮，不可能让这一局跑偏。
 *
 * @param llm话 已经拿到的 AI 说法（没有就传 null → 用作者的兜底）
 */
export function 打一轮(
  局: 局状态,
  配置: 跑团配置,
  llm话: string | 描写 | null = null,
  骰: 骰子 = 真骰子,
): { 新局: 局状态; 结果: 跑团结果 } {
  const 当前 = 取回合(配置, 局.轮);
  const 骰子: [number, number] = [骰(), 骰()];
  const 修正 = 修正值(局.指标);
  const { 档, 合计 } = 判定(骰子, 修正, 当前.难度);
  const 果 = 当前.后果[档];
  const 好 = 归一(llm话);

  const 指标: 指标增量 = {
    信任: 果.信任 ?? 0,
    协作: 果.协作 ?? 0,
    成长: 果.成长 ?? 0,
  };
  const 命中 = 档 === '大成功' || 档 === '成功';
  const 新指标: 指标增量 = {
    信任: 局.指标.信任 + 指标.信任,
    协作: 局.指标.协作 + 指标.协作,
    成长: 局.指标.成长 + 指标.成长,
  };
  const 轮 = 局.轮 + 1;
  const 新命中 = 局.命中 + (命中 ? 1 : 0);
  const 新失误 = 局.失误 + (命中 ? 0 : 1);

  let 局况: 局况 = '进行中';
  if (新命中 >= 配置.通关命中) 局况 = '通关';
  else if (新失误 >= 配置.翻车失败) 局况 = '翻车';
  else if (轮 >= 配置.上限) 局况 = '超时';

  // 台词的三层来源：AI 给的（过闸了）→ 作者给这一档写的兜底 → 没有。
  // ⚠️ 必须是 `好?.对白 ?? 果.对白` 而不是 `好 ? 好.对白 : 果.对白`：
  //    AI 可能只写好了镜头、台词那句被 校验对白 挡下来了（`过闸` 会把对白摘成 undefined）。
  //    这时候要**退回作者写的兜底台词**，而不是让这一轮没有台词。
  const 对白 = 好?.对白 ?? 果.对白;
  const 谁说 = 对白 ? 果.谁说 ?? 当前.在场[0] : undefined;

  const 结果: 跑团结果 = {
    档,
    骰子,
    修正,
    合计,
    难度: 当前.难度,
    场景: 当前.场景,
    行动: 当前.行动,
    叙述: 好 ? 好.叙述 : 果.叙述,
    对白,
    谁说,
    来源: 好 ? 'AI' : '兜底',
    指标,
    线索: 果.线索,
  };

  return {
    新局: {
      轮,
      命中: 新命中,
      失误: 新失误,
      指标: 新指标,
      线索: 果.线索 ? [...局.线索, 果.线索] : 局.线索,
      局况,
      日志: [...局.日志, 结果],
    },
    结果,
  };
}

/**
 * 把**迟到的 AI 说法**贴到已经算完的那一轮上。
 *
 * 为什么要这个：跑团是"边玩边生成"，不能让玩家等模型。
 * 所以流程是 ① 引擎立刻算 + 立刻显示作者兜底的那句 → ② AI 回来了再换掉那一句。
 * 这个函数就是第 ② 步，**它只改文字，别的字段一个都不动**
 * （分数、线索、局况全在 ① 就定死了）。
 */
export function 贴AI话(局: 局状态, 叙述: string, 对白?: string): 局状态 {
  const 日志 = [...局.日志];
  const 尾 = 日志[日志.length - 1];
  if (!尾) return 局;
  const 干净 = 叙述.trim();
  if (!干净) return 局;
  日志[日志.length - 1] = { ...尾, 叙述: 干净, 对白: 对白?.trim() || 尾.对白, 来源: 'AI' };
  return { ...局, 日志 };
}

/* ───────── 给 AI 的约束（提示词 + 校验） ───────── */

/** 传给提示词的"现在打到哪儿了" */
export interface 提示上下文 {
  轮?: number;
  上限?: number;
  命中?: number;
  失误?: number;
  线索?: string[];
  /** 上一轮的镜头，用来接住语气（AI 靠它"续上"） */
  上一句?: string | null;
}

/**
 * 系统提示词。
 *
 * 五道锁：
 *   一、**只准描述这一句**：结果已经定了，AI 不许改
 *   二、**只准输出 JSON、字段封闭**：不要散文，方便机器校验
 *   三、**台词只能出自"在场名单"**：名单由作者写死
 *   四、**明令禁项**：不提分数、不提知乎、不加新人物、不写后续
 *   五、**给出剧情进度**：让 AI 知道这是第几轮、已经拿到什么线索，
 *       话说出来才贴着这一段戏，而不是每轮都从零开始泛泛而谈
 */
export function 造提示词(
  配置: 跑团配置,
  回合: 回合,
  档: 判定档,
  人名表: string[],
  上下文: 提示上下文 = {},
): string {
  const 进度 =
    上下文.轮 === undefined
      ? ''
      : `【打到哪了】第 ${上下文.轮 + 1} 轮 / 共 ${上下文.上限 ?? '?'} 轮；已命中 ${上下文.命中 ?? 0} 次、失误 ${上下文.失误 ?? 0} 次。`;
  const 线索 =
    上下文.线索 && 上下文.线索.length
      ? `【这一局已经拿到的线索】${上下文.线索.join('；')}`
      : '【这一局还没拿到线索】';
  const 接住 = 上下文.上一句 ? `【上一轮的画面，接住它的语气】${上下文.上一句}` : '';

  return [
    '你在给一个中文职场小游戏当"跑团主持人"，同时负责写一小段小说镜头和一句人物台词。',
    '',
    '【世界观】所有角色都是白色北极狐（知乎 IP 刘看山体系），现代中国办公室。主角是刚入职的实习生刘看山。',
    `【这一局的剧情背景】${配置.背景}`,
    `【本局目标】${配置.目标}`,
    进度,
    线索,
    `【当前场景】${回合.场景}`,
    `【这一轮在场的人（只有这些人能说话）】${回合.在场.join('、')}`,
    回合.谈的是 ? `【这一轮在谈什么】${回合.谈的是}` : '',
    `【玩家这一轮的行动】${回合.行动}`,
    `【已经掷过骰子，结果已定】${档}`,
    接住,
    '',
    '【你要做的两件事】',
    '1.「叙述」：用一到两句话描写"这个结果发生时的画面"，像小说里的一个镜头。',
    '2.「对白」：让【在场的人】里的某一个人说一句话，要口语、有性格、能推进这一轮的气氛。',
    '',
    '【硬性要求】',
    '1. 只输出 JSON，不要任何解释文字：{"叙述":"...","对白":"..."}',
    '2. 叙述 30~60 个汉字，以句号结尾。',
    '3. 对白 6~24 个汉字，不加引号、不写"某某说"，直接写这句话本身。',
    '4. 叙述必须与给定结果一致：成功就往顺利里写，失败就往卡住/出错里写，不要"虽然失败但意外成功"这种翻盘。',
    `5. 只准出现这些人：${人名表.join('、')}。不要新增任何人物、客户、领导或部门。`,
    '6. 不要写出任何数字、分数、命中/失败次数、骰子点数。',
    '7. 不要提"知乎"、不要引用任何文章或链接。',
    '8. 不要推进剧情：不要揭示后面的情节、不要替玩家做决定、不要出现"从此以后"这种收束语气。',
    '9. 不要写心理分析，不要点评玩家的选择对错，不要在台词里给出结论式的道理。',
    '10. 台词要像真人在办公室说话：有口头语、有停顿感，别写成标语。',
  ]
    .filter((x) => x !== '')
    .join('\n');
}

/** 命中的禁词（出现在 AI 的叙述里就直接退回兜底） */
const 禁词 = ['知乎', '分数', '骰子', '命中', '指标', '信任值', '协作值', '成长值', '大成功', '大失败'];

/** 允许出现的人名（AI 提到别的人名就退回兜底） */
const 常见越界人名 = ['老板的老板', 'HR', '前台小妹', '保安', '新来的实习生'];

/**
 * 允许出现的"非人名角色"。
 * 这些是**剧情里本来就有**的：客户就是程女士，「同事」「大家」是泛指，
 * 不能被"越界人名"那条误杀（第一版把"客户"当越界拦掉了，
 * 结果连脚本自己写的兜底叙述都过不了闸 —— 自检里抓到的）。
 */
const 允许泛称 = ['客户', '同事', '大家', '老板', '对方', '他们', '你们', '我们'];

export interface 校验结果 {
  过: boolean;
  理由?: string;
}

/**
 * 校验 AI 的镜头描写。
 * 宁可退回兜底，也不要放一句奇怪的话进去 —— 这是"不偏离"的最后一道闸。
 */
export function 校验叙述(文: unknown, 允许人名: string[]): 校验结果 {
  if (typeof 文 !== 'string') return { 过: false, 理由: '不是字符串' };
  const s = 文.trim();
  if (!s) return { 过: false, 理由: '空' };
  if (s.length < 12) return { 过: false, 理由: '太短' };
  if (s.length > 120) return { 过: false, 理由: '太长' };
  if (/[A-Za-z]{4,}/.test(s)) return { 过: false, 理由: '混进了英文' };
  for (const k of 禁词) if (s.includes(k)) return { 过: false, 理由: `出现禁词「${k}」` };
  // 不许写分数：**不要笼统地禁数字**（"第 3 稿""15:30"这种正当代词很多），
  // 只禁"数字紧挨着加减号"和"加减号 + 数字"这种数值写法（+2 / -1 / 加 2）
  if (/[+\-]\s*\d/.test(s) || /(加|减)\s*\d/.test(s)) {
    return { 过: false, 理由: '写成了数值增减' };
  }
  for (const k of 常见越界人名) {
    if (允许泛称.includes(k)) continue; // 泛指（客户/同事/大家）不算越界
    if (s.includes(k) && !允许人名.includes(k)) return { 过: false, 理由: `出现了没安排的人「${k}」` };
  }
  // 不许把结果写成"翻盘"
  if (/虽然.{0,6}(失败|没成).{0,8}(但|却).{0,6}(成功|成了|反而)/.test(s)) {
    return { 过: false, 理由: '把失败写成了翻盘' };
  }
  return { 过: true };
}

/**
 * 把 `程女士：「……」` / `程女士说：……` 这种前缀剥掉，返回纯台词。
 * 模型很爱写成这样，不剥的话台词会带着半截格式显示出来。
 */
export function 剥前缀(文: string, 在场: string[]): string {
  let s = 文.trim();
  for (const 名 of 在场) {
    if (!s.startsWith(名)) continue;
    s = s
      .slice(名.length)
      .replace(/^\s*(说|问|答|道|喊|笑|叹气|低声说|说道)?\s*[:：,，]?\s*/, '')
      .trim();
  }
  s = s.replace(/^[「『"'“‘]+/, '').replace(/[」』"'”’]+$/, '').trim();
  return s;
}

/**
 * 校验 AI 的那句台词。
 *
 * 比对白本身更重要的两件事：
 *   一、**台词必须出自"在场的人"** —— 名单由作者写死，这是"不偏离剧情"的核心。
 *       做法是：把台词前缀剥掉后，只要它没有冒出"没安排的人名"就放行
 *       （我们**不要求**模型在 JSON 里报"谁说的"：那样更容易被它编出来，
 *        由剧本按档位决定 谁说 反而更可控 —— 见 后果.谁说）。
 *   二、**台词里不能出现禁词、数值增减、英文**
 */
export function 校验对白(文: unknown, 在场: string[], 允许人名: string[]): 校验结果 {
  if (typeof 文 !== 'string') return { 过: false, 理由: '不是字符串' };
  const s = 剥前缀(文, 在场);
  if (!s) return { 过: false, 理由: '空' };
  if (s.length < 4) return { 过: false, 理由: '太短' };
  if (s.length > 40) return { 过: false, 理由: '太长' };
  if (/[A-Za-z]{4,}/.test(s)) return { 过: false, 理由: '混进了英文' };
  for (const k of 禁词) if (s.includes(k)) return { 过: false, 理由: `出现禁词「${k}」` };
  if (/[+\-]\s*\d/.test(s) || /(加|减)\s*\d/.test(s)) {
    return { 过: false, 理由: '写成了数值增减' };
  }
  for (const k of 常见越界人名) {
    if (允许泛称.includes(k)) continue;
    if (s.includes(k) && !允许人名.includes(k)) return { 过: false, 理由: `台词里出现了没安排的人「${k}」` };
  }
  return { 过: true };
}

/**
 * 一句话把 AI 的返回过完两道闸。
 * 返回 null 表示"这次不用 AI"，调用方用作者兜底。
 */
export function 过闸(
  回: { 叙述?: unknown; 对白?: unknown } | null,
  在场: string[],
  允许人名: string[],
): 描写 | null {
  if (!回) return null;
  const 叙述 = typeof 回.叙述 === 'string' ? 回.叙述.trim() : '';
  if (!校验叙述(叙述, 允许人名).过) return null;
  const 对白 = typeof 回.对白 === 'string' ? 剥前缀(回.对白, 在场) : '';
  const 对白可用 = 对白 ? 校验对白(对白, 在场, 允许人名).过 : false;
  return { 叙述, 对白: 对白可用 ? 对白 : undefined };
}

