/**
 * 跑团式的「不偏离剧情的随机对话」。
 *
 * 用户问：「如果后续剧情会出现类似跑团的剧情，可以接入知乎 llm 模型来做不偏离剧情的随机对话」。
 *
 * 能。但关键在于**把"随机"关进笼子里** —— 这一层做的就是那个笼子：
 *
 *   ┌─ 引擎（本文件，纯逻辑、可离线单测）────────────────────────┐
 *   │  掷骰 → 判定 → **结果只有四种**（大成功/成功/失败/大失败）   │
 *   │  每种结果**已经写好了确定性的后果**（指标、线索、下一轮修正） │
 *   └───────────────────────────────────────────────────────┘
 *                              ↓ 只把"结果"告诉 AI
 *   ┌─ AI（`llm.ts`，可以没有 / 可以挂 / 可以超时）──────────────┐
 *   │  只负责**把这一句描写说得好听**：一轮一句、不许新增事实     │
 *   └───────────────────────────────────────────────────────┘
 *                              ↓ 校验
 *   ┌─ 兜底（`兜底叙述`）───────────────────────────────────┐
 *   │  校验不过 / 超时 / 没配密钥 → 用预写好的那句话           │
 *   └───────────────────────────────────────────────────────┘
 *
 * 所以**离线也一定是完整的一局**：AI 只是给同一局换一层皮。
 * ⚠️ 铁律：AI **不得**改分数、不得新增人物/线索、不得决定成败、不得编造知乎来源。
 */

/* ───────── 类型 ───────── */

/** 判定的结果档位。**只有这四种**，AI 无权新增 —— 这是"不偏离剧情"的根 */
export type 判定档 = '大成功' | '成功' | '失败' | '大失败';

/** 一回合的脚本：作者手写，AI 不许碰 */
export interface 回合 {
  /** 场景名（给 AI 的上下文用，例如「文印区 · 打印机卡纸」） */
  场景: string;
  /** 玩家这一轮要干的事（给 AI 的上下文用） */
  行动: string;
  /** 难度：掷骰 + 修正 ≥ 难度 才算成功 */
  难度: number;
  /** **确定性后果**：每种档位写死"发生什么"。AI 只描述，不改这个。 */
  后果: Record<判定档, { 叙述: string; 信任?: number; 协作?: number; 成长?: number; 线索?: string }>;
}

export interface 跑团配置 {
  id: string;
  /** 这一段的目标（AI 的上下文，也是玩家的目标） */
  目标: string;
  /** 回合上限（G5：15 轮上限） */
  上限: number;
  /** 命中多少次算通关（G5：第 4 章是 3 次） */
  通关命中: number;
  /** 连续失败多少次算翻车（G5） */
  翻车失败: number;
  回合: 回合[];
}

export interface 指标增量 {
  信任: number;
  协作: number;
  成长: number;
}

export interface 跑团结果 {
  档: 判定档;
  /** 这一轮的骰面（2d6 两颗） */
  骰子: [number, number];
  修正: number;
  合计: number;
  难度: number;
  /** 实际发出去的叙述（可能是 AI 的，也可能是兜底的） */
  叙述: string;
  来源: 'AI' | '兜底';
  /** 指标增量（**只来自脚本，与 AI 无关**） */
  指标: 指标增量;
  线索?: string;
}

export type 局况 = '进行中' | '通关' | '翻车' | '超时';

/* ───────── 掷骰与判定 ───────── */

/** 可注入的骰子（测试时换成固定序列，就能复现"连续大失败"这种边角）*/
export type 骰子 = () => number;
const 真骰子: 骰子 = () => 1 + Math.floor(Math.random() * 6);

/** 指标 → 掷骰修正：某一项越高越容易过（+0~+3） */
export function 修正值(指标: 指标增量): number {
  const 总 = 指标.信任 + 指标.协作 + 指标.成长;
  return Math.max(0, Math.min(3, Math.floor(总 / 9)));
}

/**
 * 判定。
 * ⚠️ 这里**只认骰子和难度**，不看 AI 说了什么 —— 顺序绝不能反。
 */
export function 判定(骰: [number, number], 修正: number, 难度: number): { 档: 判定档; 合计: number } {
  const 合计 = 骰[0] + 骰[1] + 修正;
  if (骰[0] === 6 && 骰[1] === 6) return { 档: '大成功', 合计 };
  if (骰[0] === 1 && 骰[1] === 1) return { 档: '大失败', 合计 };
  return { 档: 合计 >= 难度 ? '成功' : '失败', 合计 };
}

/* ───────── 一局的进度 ───────── */

export interface 局状态 {
  轮: number;
  命中: number;
  失误: number;
  指标: 指标增量;
  线索: string[];
  局况: 局况;
  /** 已经打过的叙述（回看用） */
  日志: 跑团结果[];
}

export function 开局(): 局状态 {
  return { 轮: 0, 命中: 0, 失误: 0, 指标: { 信任: 0, 协作: 0, 成长: 0 }, 线索: [], 局况: '进行中', 日志: [] };
}

/** 取这一轮该用的脚本（超过脚本长度就循环用最后一条，方便少写几条）*/
export function 取回合(配置: 跑团配置, 轮: number): 回合 {
  return 配置.回合[Math.min(轮, 配置.回合.length - 1)] as 回合;
}

/**
 * 打一轮。
 *
 * ⚠️ 这是一个**纯函数**：给定（局状态, 配置, 骰子）就能算出结果，
 *    不碰网络、不碰 AI。AI 的叙述是**算完之后**再贴上去的（见 useStory / 调用方）。
 *    这样"AI 挂了"永远只是少一层皮，不可能让这一局跑偏。
 */
export function 打一轮(
  局: 局状态,
  配置: 跑团配置,
  llm叙述: string | null = null,
  骰: 骰子 = 真骰子,
): { 新局: 局状态; 结果: 跑团结果 } {
  const 当前 = 取回合(配置, 局.轮);
  const 骰子: [number, number] = [骰(), 骰()];
  const 修正 = 修正值(局.指标);
  const { 档, 合计 } = 判定(骰子, 修正, 当前.难度);
  const 果 = 当前.后果[档];

  const 指标: 指标增量 = {
    信任: 果.信任 ?? 0,
    协作: 果.协作 ?? 0,
    成长: 果.成长 ?? 0,
  };
  const 命中 = 档 === '大成功' || 档 === '成功';
  const 新指标: 指标增量 = {
    信任: 局.指标.信任 + 指标.信任,
    协作: 局.指标.协作 + 指标.协作,
    成长: 局.指标.成长 + 指标.成长,
  };
  const 轮 = 局.轮 + 1;
  const 新命中 = 局.命中 + (命中 ? 1 : 0);
  const 新失误 = 局.失误 + (命中 ? 0 : 1);

  let 局况: 局况 = '进行中';
  if (新命中 >= 配置.通关命中) 局况 = '通关';
  else if (新失误 >= 配置.翻车失败) 局况 = '翻车';
  else if (轮 >= 配置.上限) 局况 = '超时';

  const 结果: 跑团结果 = {
    档,
    骰子,
    修正,
    合计,
    难度: 当前.难度,
    叙述: llm叙述 ?? 果.叙述,
    来源: llm叙述 ? 'AI' : '兜底',
    指标,
    线索: 果.线索,
  };

  return {
    新局: {
      轮,
      命中: 新命中,
      失误: 新失误,
      指标: 新指标,
      线索: 果.线索 ? [...局.线索, 果.线索] : 局.线索,
      局况,
      日志: [...局.日志, 结果],
    },
    结果,
  };
}

/* ───────── 给 AI 的约束（提示词 + 校验） ───────── */

/**
 * 系统提示词。
 *
 * 三道锁：
 *   一、**只准描述这一句**：结果已经定了，AI 不许改
 *   二、**只准输出 JSON、字段封闭**：不要散文，方便机器校验
 *   三、**明令禁项**：不提分数、不提知乎、不加新人物、不写后续
 */
export function 造提示词(配置: 跑团配置, 回合: 回合, 档: 判定档, 人名表: string[]): string {
  return [
    '你在给一个中文职场小游戏当"跑团主持人"。',
    '',
    '【世界观】所有角色都是白色北极狐（知乎 IP 刘看山体系），现代中国办公室。主角是刚入职的实习生刘看山。',
    `【本局目标】${配置.目标}`,
    `【当前场景】${回合.场景}`,
    `【玩家这一轮的行动】${回合.行动}`,
    `【已经掷过骰子，结果已定】${档}`,
    '',
    '【你只做一件事】用**一到两句话**描写"这个结果发生时的画面"，像小说里的一个镜头。',
    '',
    '【硬性要求】',
    '1. 只输出 JSON，不要任何解释文字：{"叙述":"..."}',
    '2. 叙述 30~60 个汉字，以句号结尾。',
    '3. 叙述必须与给定结果一致：成功就往顺利里写，失败就往卡住/出错里写，不要"虽然失败但意外成功"这种翻盘。',
    `4. 只准出现这些人：${人名表.join('、')}。不要新增任何人物、客户、领导或部门。`,
    '5. 不要写出任何数字、分数、命中/失败次数、骰子点数。',
    '6. 不要提"知乎"、不要引用任何文章或链接。',
    '7. 不要推进剧情：不要揭示后面的情节、不要替玩家做决定、不要出现"从此以后"这种收束语气。',
    '8. 不要写对白以外的心理分析，不要点评玩家的选择对错。',
  ].join('\n');
}

/** 命中的禁词（出现在 AI 的叙述里就直接退回兜底） */
const 禁词 = ['知乎', '分数', '骰子', '命中', '指标', '信任值', '协作值', '成长值', '大成功', '大失败'];

/** 允许出现的人名（AI 提到别的人名就退回兜底） */
const 常见越界人名 = ['老板的老板', 'HR', '前台小妹', '保安', '新来的实习生'];

/**
 * 允许出现的"非人名角色"。
 * ⚠️ 这些是**剧情里本来就有**的：客户就是程女士，「同事」「大家」是泛指，
 *    不能被"越界人名"那条误杀（第一版把"客户"当越界拦掉了，
 *    结果连脚本自己写的兜底叙述都过不了闸 —— 自检里抓到的）。
 */
const 允许泛称 = ['客户', '同事', '大家', '老板', '对方', '他们', '你们', '我们'];

export interface 校验结果 {
  过: boolean;
  理由?: string;
}

/**
 * 校验 AI 的一句话。
 * ⚠️ 宁可退回兜底，也不要放一句奇怪的话进去 —— 这是"不偏离"的最后一道闸。
 */
export function 校验叙述(文: unknown, 允许人名: string[]): 校验结果 {
  if (typeof 文 !== 'string') return { 过: false, 理由: '不是字符串' };
  const s = 文.trim();
  if (!s) return { 过: false, 理由: '空' };
  if (s.length < 12) return { 过: false, 理由: '太短' };
  if (s.length > 120) return { 过: false, 理由: '太长' };
  if (/[A-Za-z]{4,}/.test(s)) return { 过: false, 理由: '混进了英文' };
  for (const k of 禁词) if (s.includes(k)) return { 过: false, 理由: `出现禁词「${k}」` };
  // 不许写分数：**不要笼统地禁数字**（"第 3 稿""15:30"这种正当代词很多），
  // 只禁"数字紧挨着加减号"和"加减号 + 数字"这种数值写法（+2 / -1 / 加 2）
  if (/[+\-]\s*\d/.test(s) || /(加|减)\s*\d/.test(s)) {
    return { 过: false, 理由: '写成了数值增减' };
  }
  for (const k of 常见越界人名) {
    if (允许泛称.includes(k)) continue; // 泛指（客户/同事/大家）不算越界
    if (s.includes(k) && !允许人名.includes(k)) return { 过: false, 理由: `出现了没安排的人「${k}」` };
  }
  // 不许把结果写成"翻盘"
  if (/虽然.{0,6}(失败|没成).{0,8}(但|却).{0,6}(成功|成了|反而)/.test(s)) {
    return { 过: false, 理由: '把失败写成了翻盘' };
  }
  return { 过: true };
}

