/**
 * 剧情数据结构。
 *
 * 设计：剧本是一串扁平的「节拍」（Beat），引擎顺序播放。
 * 选择（选择）内部嵌一段子节拍，所以分支不需要引擎特殊处理 —— 播完子节拍就汇合。
 *
 * 换行间隔（间隔）单位是毫秒；不给就用全局默认（G1：0.8~4 秒不等）。
 */

/** 剧情里会说话的人。头像素材按这个名字找。 */
export type 说话人 =
  | '刘看山'
  | '林总'
  | '周岚'
  | '阿麦'
  | '韩策'
  | '小鹿'
  | '程女士'
  | '学长'
  | '系统'
  | '旁白';

/** 三项指标（G9） */
export interface 指标 {
  信任: number;
  协作: number;
  成长: number;
}

export type 指标增减 = Partial<指标>;

/** 头像用的表情名。找不到就退回默认表情。 */
export type 表情名 = string;

/** 贴纸素材名，对应 成品/界面v2/贴纸_<名>.png */
export type 贴纸名 =
  | '探头' | '点赞' | '大哭' | '震惊' | '合十' | '递咖啡'
  | '抱头' | '举手' | '晕' | '比心' | '累了' | '鞠躬';

/** 一个选项 */
export interface 选项 {
  /** 按钮上显示的短标签，例如「说出自己的来处和看法」 */
  标签: string;
  /** 选中后要播放的节拍 */
  内容: 节拍[];
  /** 可选：直接给出的指标增减（也可以在内容里用 指标 节拍给） */
  效果?: 指标增减;
}

export type 节拍 =
  /** 旁白 / 舞台指示。会显示在插图下方的叙述条上。 */
  | { 类型: '旁白'; 文本: string; 间隔?: number }
  /** 切到某个会话（不存在就新建）。之后的「消息 / 贴纸 / 输入中」都发到这里。 */
  | {
      类型: '切会话';
      id: string;
      名字: string;
      会话类型: '私聊' | '群聊';
      /** 私聊时的对方；群聊不填 */
      对方?: 说话人;
      /** 群聊成员，用来拼 2×2 群头像 */
      成员?: 说话人[];
    }
  /** 一条聊天消息。谁 + 文本。 */
  | { 类型: '消息'; 谁: 说话人; 文本: string; 间隔?: number }
  /** 「某某 正在输入…」。只在私聊用（G2）。 */
  | { 类型: '输入中'; 谁: 说话人; 间隔?: number }
  /** 贴纸消息。 */
  | { 类型: '贴纸'; 谁: 说话人; 贴纸: 贴纸名; 间隔?: number }
  /** 系统提示行（居中、灰字）。 */
  | { 类型: '系统'; 文本: string; 间隔?: number }
  /** 群聊邀请卡，需要玩家点按钮。 */
  | { 类型: '邀请'; 标题: string; 副标题: string; 按钮: string }
  /** 换插图（场景切换）。 */
  | { 类型: '场景'; 插图: string }
  /** 三项指标变动。会飘一行提示。 */
  | { 类型: '指标'; 变动: 指标增减 }
  /** 一张知乎卡（角色主动转发，或收束时发放）。 */
  | { 类型: '知乎卡'; 卡片: 知乎卡数据 }
  /** 三选一（G4：选定即播放，不可撤销） */
  | { 类型: '选择'; 选项: 选项[] }
  /** 章节标题卡 */
  | { 类型: '标题'; 标题: string; 副标题?: string }
  /** 这一段的结束标记；播放到这里就停下等外部推进 */
  | { 类型: '暂停'; 提示: string };

/**
 * 一张知乎卡的数据。
 *
 * ⚠️ 内容必须来自真实知乎检索，**不许编造**。
 * 现在留空占位，接入真实内容时把 已接入 改成 true 并填字段。
 */
export interface 知乎卡数据 {
  /** 主题，显示在卡片顶部 */
  主题: string;
  /** 是否已经填入真实内容 */
  已接入: boolean;
  /** 文章/回答标题 */
  标题?: string;
  /** 作者名 */
  作者?: string;
  /** 原文摘录（搜索返回的 ContentText，不是全文） */
  摘录?: string;
  /** 原始链接（已剥掉追踪参数） */
  链接?: string;
  /** 赞同数 */
  赞同?: number;
}

/** 一段剧本 */
export interface 剧本段 {
  id: string;
  /** 场景插图（先给一个默认，后面可以用 场景 节拍换） */
  插图: string;
  /** 这一段的节拍 */
  节拍: 节拍[];
}

/** 开场动画的一格镜头 */
export interface 开场镜 {
  /** 插图素材 key（对应 素材表 的 key，例如 背景/章节封面_横版） */
  插图: string;
  /** 叠在图上的大字 */
  大字?: string;
  /** 叠在图上的小字 */
  小字?: string;
  /** 停留毫秒 */
  停留: number;
  /** 动效 */
  动效?: '淡入' | '推近' | '黑场';
}
