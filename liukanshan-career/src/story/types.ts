/**
 * 剧情数据结构。
 *
 * 设计：剧本是一串扁平的「节拍」（Beat），引擎顺序播放。
 * 选择（选择）内部嵌一段子节拍，所以分支不需要引擎特殊处理 —— 播完子节拍就汇合。
 *
 * 换行间隔（间隔）单位是毫秒；不给就用全局默认（G1：0.8~4 秒不等）。
 */

import type { 跑团配置 } from './跑团';

/** 剧情里会说话的人。头像素材按这个名字找。 */
export type 说话人 =
  | '刘看山'
  | '林总'
  | '周岚'
  | '阿麦'
  | '韩策'
  | '小鹿'
  | '程女士'
  | '学长'
  | '系统'
  | '旁白';

/** 三项指标（G9） */
export interface 指标 {
  信任: number;
  协作: number;
  成长: number;
}

export type 指标增减 = Partial<指标>;

/** 头像用的表情名。找不到就退回默认表情。 */
export type 表情名 = string;

/** 贴纸素材名，对应 成品/界面v2/贴纸_<名>.png */
export type 贴纸名 =
  | '探头' | '点赞' | '大哭' | '震惊' | '合十' | '递咖啡'
  | '抱头' | '举手' | '晕' | '比心' | '累了' | '鞠躬';

/** 一个选项 */
export interface 选项 {
  /** 按钮上显示的短标签，例如「说出自己的来处和看法」 */
  标签: string;
  /** 选中后要播放的节拍 */
  内容: 节拍[];
  /** 可选：直接给出的指标增减（也可以在内容里用 指标 节拍给） */
  效果?: 指标增减;
}

export type 节拍 =
  /** 旁白 / 舞台指示。会显示在插图下方的叙述条上。 */
  | { 类型: '旁白'; 文本: string; 间隔?: number }
  /**
   * **时间提示**（只显示时间，不显示剧情旁白）。
   *
   * 用户要求：AVG 里"只显示时间提示，不显示旁白"。所以：
   *   · 时间 / 日期这种"给玩家定位"的信息 → 用这一条，聊天区正中一行小灰字
   *   · 真正的**剧情旁白**（「群里安静了四秒」「告状换不来信任」这种）→ **删掉不写**
   *     （不是藏起来 —— 剧本里就不该有，见交接文档"AVG 只显示对话与时间"）
   * 引擎里它和「系统」走同一条渲染路径，只是样式不同，好让 UI 能分开调。
   */
  | { 类型: '时间'; 文本: string; 间隔?: number }
  /** 切到某个会话（不存在就新建）。之后的「消息 / 贴纸 / 输入中」都发到这里。 */
  | {
      类型: '切会话';
      id: string;
      名字: string;
      会话类型: '私聊' | '群聊';
      /** 私聊时的对方；群聊不填 */
      对方?: 说话人;
      /** 群聊成员，用来拼 2×2 群头像 */
      成员?: 说话人[];
    }
  /** 一条聊天消息。谁 + 文本。 */
  | {
      类型: '消息';
      谁: 说话人;
      文本: string;
      间隔?: number;
      /** 被撤回了（界面把它渲染成「<撤回者>撤回了一条消息」） */
      已撤回?: boolean;
      /** 谁撤的（群聊里组长能撤别人的消息 —— 文档第 7 条就是这个情境） */
      撤回者?: 说话人;
    }
  /** 「某某 正在输入…」。只在私聊用（G2）。 */
  | { 类型: '输入中'; 谁: 说话人; 间隔?: number }
  /** 贴纸消息。 */
  | { 类型: '贴纸'; 谁: 说话人; 贴纸: 贴纸名; 间隔?: number }
  /** 系统提示行（居中、灰字）。 */
  | { 类型: '系统'; 文本: string; 间隔?: number }
  /** 群聊邀请卡，需要玩家点按钮。
   *  `会话id` = 这个邀请属于哪个会话（一般是紧跟其后的那条「切会话」的 id）。
   *  有了它，邀请卡才能画在**正确的群里**并给那个会话加未读红点。 */
  | { 类型: '邀请'; 标题: string; 副标题: string; 按钮: string; 会话id?: string }
  /** 换插图（场景切换）。 */
  | { 类型: '场景'; 插图: string }
  /** 三项指标变动。会飘一行提示。 */
  | { 类型: '指标'; 变动: 指标增减 }
  /** 一张知乎卡（角色主动转发，或收束时发放）。 */
  | { 类型: '知乎卡'; 卡片: 知乎卡数据 }
  /** 三选一（G4：选定即播放，不可撤销） */
  | { 类型: '选择'; 选项: 选项[] }
  /**
   * **过场动画**（文档第 0/1/3 条）。
   *
   * 用户要求：「坐椅子和下椅子需要做成一个常用功能，**第一次坐上椅子，进入过场动画**」、
   * 「在**每次任务之间**加一段过场动画」、「"不要害怕，他又不吃人"之后，**进一段过场动画**，
   * 之后再弹茶水间事件」。
   *
   * 它是一个**全屏的过场层**（黑底 + 时间/地点字幕 + 进度条），盖住所有屏幕
   * （包括地图 —— "坐到工位上"这件事本身就发生在地图上）。
   * 时长走完自动继续，玩家不用点任何东西。
   */
  | {
      类型: '过场';
      /** 大字：地点或时间，例如「办公室 · 我的工位」 */
      标题: string;
      /** 小字：一句过场说明，例如「坐下的那一刻，你才真的成为了这里的人」 */
      副标题?: string;
      /** 插图（可选，走 UI 的素材表） */
      插图?: string;
      /** 持续秒数，默认 2.6 */
      秒?: number;
    }
  /**
   * **停下来等玩家自己说一句话**（文档第 7 条）。
   *
   * 用户要求：「在周岚撤回信息之前，应该出现一个文字框，并提示玩家:
   * 试着在这里发送一句话吧，之后等玩家发送出去，周岚才会将它撤回，并私聊。」
   *
   * 引擎效果：位置推进过这一条，但把 `待玩家发言` 立起来（界面出输入框）——
   * 玩家点发送之后才继续往下播（和「选择」同一个套路：**不选就不往下走**）。
   */
  | { 类型: '等玩家发言'; 提示: string; 间隔?: number }
  /**
   * **撤回一条消息**（文档第 7 条）。
   *
   * 效果：把**这个会话里最后一条"我方"消息**标成已撤回 ——
   * 界面上它变成一行「<谁>撤回了一条消息」（微信就是这么显示的）。
   * ⚠️ 原来剧本里是直接写一句 `系统: '周岚撤回了一条消息'` —— 那句**没有可撤回的对象**，
   *    看着莫名其妙（玩家根本没发过消息，周岚撤回了个啥）。
   */
  | { 类型: '撤回'; 谁: 说话人; 间隔?: number }
  /** 章节标题卡 */
  | { 类型: '标题'; 标题: string; 副标题?: string }
  /** 这一段的结束标记；播放到这里就停下等外部推进 */
  | { 类型: '暂停'; 提示: string }
  /**
   * **去某个房间**（房间内的场景切换）。
   *
   * 用户要求：「这种切换场景的情况要切换到 2D 模式、走到对应的房间场景再继续，
   * 就像走到自己的工位上」。
   *
   * 效果：① 屏幕切回地图 ② 指引线指向 `去哪`（交互点 id）③ 停在队列这一条上不动
   * ④ 玩家走到那儿按空格 → **从下一条继续播**（不会重播已经播过的内容）。
   *
   * ⚠️ 和「暂停 + 段号推进」不是一回事：
   *    `暂停` 是"这一段演完了，去地图触发**下一段**"（`地图入口`）；
   *    `去房间` 是"**这一段还没演完**，先走过去"（`地图目标` = 去哪）。
   *    引擎里用 `续播` 这个字段区分这两件事。
   */
  | { 类型: '去房间'; 去哪: string; 提示: string }
  /**
   * **跑团式的一段戏**（掷骰 + AI 描写，见 `跑团.ts`）。
   *
   * 播到这一条就停下、把屏幕交给 `跑团面板`：玩家一轮一轮掷骰，
   * 通关 / 翻车 / 超时之后由 `跑团收工()` 把结果写成一条系统消息，
   * **从下一条继续播**（这一条不会重播）。
   *
   * ⚠️ 铁律：跑团**不改主线分支**。它的结果只影响三项指标、线索和那段文字，
   *    剧本之后怎么走和它无关 —— 这样"AI 挂了"绝不可能让玩家走进死路。
   */
  | { 类型: '跑团'; 配置: 跑团配置; 提示?: string }
  /**
   * **开小游戏**（切到 `屏幕 = 'level'` 的 Phaser 工作关）。
   *
   * 播到这一条就切屏，玩家把这一关打完；打完之后由 `关卡结束()` 切回 AVG，
   * 并把成绩写成一条系统消息，**从下一条继续播**。
   */
  | { 类型: '开小游戏'; 标题: string; 提示: string };

/**
 * 一张知乎卡的数据。
 *
 * ⚠️ 内容必须来自真实知乎检索，**不许编造**。
 * 现在留空占位，接入真实内容时把 已接入 改成 true 并填字段。
 */
export interface 知乎卡数据 {
  /** 主题，显示在卡片顶部 */
  主题: string;
  /** 是否已经填入真实内容 */
  已接入: boolean;
  /** 文章/回答标题 */
  标题?: string;
  /** 作者名 */
  作者?: string;
  /** 原文摘录（搜索返回的 ContentText，不是全文） */
  摘录?: string;
  /** 原始链接（已剥掉追踪参数） */
  链接?: string;
  /** 赞同数 */
  赞同?: number;
}

/** 一段剧本 */
export interface 剧本段 {
  /**
   * 这一段从地图上的哪个交互点启动（对应 level.ts 的 交互点 id）。
   * 空 = 紧接着上一段播（比如开场之后的第一段）。
   */
  地图入口?: string;
  /** 地图上导航指向这个点时的说明 */
  地图提示?: string;
  id: string;
  /** 场景插图（先给一个默认，后面可以用 场景 节拍换） */
  插图: string;
  /** 这一段的节拍 */
  节拍: 节拍[];
}

/** 开场动画的一格镜头 */
export interface 开场镜 {
  /** 插图素材 key（对应 素材表 的 key，例如 背景/章节封面_横版） */
  插图: string;
  /** 叠在图上的大字 */
  大字?: string;
  /** 叠在图上的小字 */
  小字?: string;
  /** 停留毫秒 */
  停留: number;
  /** 动效 */
  动效?: '淡入' | '推近' | '黑场';
  /**
   * 文字位置。默认居中。
   * 人物在画面中间的那几格（接到电话 / 写字楼门口 / 工位第一天）要用 '上'，
   * 否则大字会压在人物脸上。
   */
  文字位?: '中' | '上';
}
