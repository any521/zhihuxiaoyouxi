/** 取一张道具卡；没有就返回 null（靠近时不显示卡片，而不是显示空白） */
export function 取道具卡(图: string): 道具卡 | null {
  return 道具卡库[图] ?? null;
}

/** 有多少种道具配了卡（自检用：应该接近 道具表 里的去重种类数） */
export function 覆盖统计(): { 配了卡: number; 道具种类: number; 缺卡: string[] } {
  const 种类 = [...new Set(道具表.map((p) => p.图))];
  const 缺卡 = 种类.filter((图) => !道具卡库[图]);
  return { 配了卡: 种类.length - 缺卡.length, 道具种类: 种类.length, 缺卡 };
}

/**
 * 一件道具的**落地范围**（世界像素）。给"靠近检测"用。
 *
 * 为什么要算中心而不是拿精灵坐标：精灵的锚点在脚底（origin 0.5,1），
 * 拿那个点当中心的话，桌子这种"内容在画布上半部分"的东西，
 * 判定圈会偏下整整一格 —— 人站在桌面上方不算"靠近"。
 */
export function 道具落地范围(p: 道具位): { x: number; y: number; 宽: number; 高: number } {
  const [宽, 高] = 占地表[p.图] ?? [44 * 0.85, 48 * 0.4];
  const 中心x = p.x * 格 + 格 / 2;
  const 底y = p.y * 格 + 格 + (p.偏移Y ?? 0);
  return { x: 中心x, y: 底y - 高 / 2, 宽, 高 };
}
