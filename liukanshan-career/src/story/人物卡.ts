/** 取一张人物卡：库里没有就用通讯录档案兜底，再没有就返回 null */
export function 取人物卡(谁: 说话人): 人物卡 | null {
  const 有 = 人物卡库[谁];
  if (有) return 有;
  const 档 = 取档案(谁);
  if (!档) return null;
  return { ...档, 口风: '（这个人还没有专属对话）' };
}
