export interface 订单 {
  id: number;
  /** 这一单是谁的活（客户或内部项目） */
  客户: string;
  /** 这一单属于什么类型的活（显示在客户名字后面） */
  类型: string;
  需要: 工序[];
  /** 交付后给多少分（工序越多越高） */
  分: number;
  /**
   * **这一单还剩几秒**（场景每帧写进来的）。
   *
   * ⚠️ 用户要求：「**增加任务的时间限制**……**时间到了没做完就清除掉并且扣除分数**，
   *    **边框变红**的动画，变红后就消失同时扣分」。
   *    UI 读它做两件事：① 卡片角上显示剩余秒数 ② 快到时给卡片加 `.urgent`（红框脉冲 ✔）
   */
  剩余?: number;
}

/** 每张工单的时限（秒）。⚠️ 和上面那条需求配套 —— 超时就作废并扣分 */
export const 工单时限 = 60;

