/**
 * 开场与剧情的状态机。
 *
 * 设计：剧本是一条**扁平队列**，引擎每次 tick 取一条。
 *   遇到「选择」就停下等玩家点，选中后把子节拍**插到当前位置**，并把「选择」本身摘掉 ——
 *   所以分支不需要引擎特殊处理，播完子节拍自然汇合。
 *
 * 消息按**会话**归堆（微信式）：脚本用「切会话」决定后面几条发到哪个窗口，
 * 玩家可以在左侧会话列表里点开任意一个回看历史。
 *
 * 与游戏关卡的状态**分开存**：关卡是 Phaser 的事，剧情是 React 的事。
 */
import { create } from 'zustand';
import type { 指标, 指标增减, 节拍, 说话人, 知乎卡数据 } from '../story/types';
import { 开场镜表 } from '../story/opening';
import { 段日期, 取段 } from '../story/script';
import { 地图片段表 } from '../story/mapScenes';
import { 座位表 } from '../game/map/level';
import { 取知乎卡 } from '../story/zhihu';
import { 播放 } from '../story/audio';

/** 当前在哪个屏幕 */
export type 屏幕 = 'opening' | 'avg' | 'map';

/** 左侧功能栏的四个面板 */
export type 侧栏面板 = '会话' | '通讯录' | '设置' | '更多';

/** 屏幕上已经渲染出来的一条 */
export type 渲染项 =
  | { 种类: '消息'; id: number; 谁: 说话人; 文本: string; 我方: boolean }
  | { 种类: '贴纸'; id: number; 谁: 说话人; 贴纸: string; 我方: boolean }
  | { 种类: '系统'; id: number; 文本: string }
  | { 种类: '旁白'; id: number; 文本: string }
  /** 时间提示（只显示时间的那一行小灰字） */
  | { 种类: '时间'; id: number; 文本: string }
  | { 种类: '邀请'; id: number; 标题: string; 副标题: string; 按钮: string; 已接受: boolean }
  | { 种类: '知乎卡'; id: number; 卡片: 知乎卡数据 }
  | { 种类: '指标'; id: number; 变动: 指标增减 }
  | { 种类: '输入中'; id: number; 谁: 说话人 };

/** 一个会话（微信左侧列表的一行 + 一个聊天窗口） */
export interface 会话 {
  id: string;
  名字: string;
  类型: '私聊' | '群聊';
  /** 私聊时的对方；群聊为空 */
  对方?: 说话人;
  /** 群聊成员，用来拼群头像 */
  成员?: 说话人[];
  未读: number;
  条目: 渲染项[];
}

interface 剧情状态 {
  屏幕: 屏幕;
  开场格: number;
  /** 当前播到第几段（对应 剧本 数组）*/
  段号: number;
  /** 当前段在会话列表顶栏显示的日期标签 */
  段标签: string;

  /** 对话队列与播放位置 */
  队列: 节拍[];
  位置: number;

  /** 会话 */
  会话们: 会话[];
  /** 脚本正在往哪个会话发消息 */
  活跃会话: string;
  /** 玩家正在看哪个会话 */
  查看会话: string;
  /** 手机端：显示列表还是聊天窗口 */
  移动端面板: '列表' | '聊天';

  /** 左侧功能栏当前选中的面板 */
  侧栏面板: 侧栏面板;
  /** 个人资料卡是否打开 */
  资料卡开: boolean;
  /** 消息播放倍速（1 = 正常） */
  速度: number;
  /** 搜索面板是否打开 */
  搜索开: boolean;
  /** 搜索词 */
  搜索词: string;

  /* ── 地图模式 ── */
  /** 玩家现在靠近哪个交互点（null = 附近没有）。场景每帧回报，React 用来显示提示。 */
  附近交互点: string | null;
  /**
   * 玩家现在**旁边是什么东西** —— 地图上的「道具卡」（用户要求"一靠近就显示"）。
   *
   * 只存"种类 + 键"，**不存整张卡**：卡的内容是从 `story/道具卡.ts` 查出来的，
   * 存进 state 会让"改文案要重置存档"这种怪事发生。
   */
  附近物: { 种类: '道具' | '格子'; 键: string } | null;
  /** 玩家现在**旁边是哪位同事**（地图上弹人物卡）。null = 旁边没人。 */
  附近人: string | null;
  /** 指引线指向哪个交互点 */
  地图目标: string | null;
  /**
   * 「去房间」节拍专用：站在 `去哪` 这个交互点上按空格，**从哪一条继续播**。
   *
   * ⚠️ 为什么要单独一个字段：地图交互原来只认两种事 ——
   *    「这是下一段的入口」（开新段）和「这是支线小片段」（播完回地图）。
   *    「去房间」是第三种：**本段还没播完，走过去接着播**。
   *    没有这个字段的话，走过去按空格会被当成"不是入口、也不是支线" → 什么都不发生，
   *    或者被误判成支线，把玩家好不容易走到的地方变成放了个小片段。
   */
  续播: { 去哪: string; 从这: number } | null;
  /** 「去房间」时底部提示要显示的话（比如"小鹿在工位上等你"）。没设就用交互点自己的提示。 */
  续播提示: string | null;
  /**
   * 脚本播到「去房间」时**先停一下**，等玩家点"去 XX ▸"再切地图。
   *
   * ⚠️ 为什么要停（用户报的"打开微信被强制关闭"真正的根因）：
   *    自动推进原来会**直接播进 `去房间` 节拍**，而那条节拍会把屏幕切到地图 ——
   *    玩家刚掏出手机看消息，界面自己就跳回办公室了，体验上就是"微信被强制关闭"。
   *    现在改成：播到 `去房间` 就停下、在聊天区底下显示一个按钮，
   *    玩家点一下才真的切地图去走。**自动推进不会越过它。**
   */
  待去房间: { 去哪: string; 提示: string } | null;
  /** 正在播地图上的支线小片段（播完「收起手机」回地图，而不是推进主线） */
  支线中: boolean;

  /** 正在看谁的人物卡（null = 没开）。点头像或点地图上的同事都会开这个。 */
  看谁: 说话人 | null;

  /** 当前等待玩家操作的东西 */
  待接受邀请: { 标题: string; 副标题: string; 按钮: string; 会话id: string | null } | null;
  待选择: { 标签: string }[] | null;
  待暂停: string | null;
  指标: 指标;
  播完: boolean;

  // 动作
  推进一步: () => void;
  接受邀请: () => void;
  选择: (序号: number) => void;
  点暂停: () => void;
  跳过开场: () => void;
  查看: (会话id: string) => void;
  回列表: () => void;
  重置: () => void;
  切面板: (p: 侧栏面板) => void;
  开关资料卡: (开?: boolean) => void;
  设速度: (n: number) => void;
  开搜索: (开: boolean) => void;
  设搜索词: (词: string) => void;

  /* ── 地图模式 ── */
  /** 场景回报"附近有哪个交互点" */
  设附近: (id: string | null) => void;
  /** 场景回报"旁边是什么东西"（道具卡） */
  设附近物: (物: { 种类: '道具' | '格子'; 键: string } | null) => void;
  /** 场景回报"旁边是哪位同事"（人物卡） */
  设附近人: (名: string | null) => void;
  /** 走到交互点按下交互：主线入口就开主线，否则播支线片段 */
  地图交互: (id: string) => void;
  /** 从手机回地图 */
  回地图: () => void;
  /** 从地图掏手机（Esc）*/
  掏手机: () => void;
  /** 打开/关闭某个人的人物卡 */
  看人物: (谁: 说话人 | null) => void;
  /** 「去房间」那一步：玩家点了"去 XX"才真的切地图 */
  去房间: () => void;
  /** 附近的门（MapScreen 用来把底部提示改成"空格 开门/关门"） */
  附近门: { x: number; y: number; 开: boolean } | null;
  设附近门: (门: { x: number; y: number; 开: boolean } | null) => void;
  /**
   * 玩家此刻是不是**正好站在一把椅子上**。
   *
   * ⚠️ 由 MapScreen 从场景读出来写进来 —— 因为"精确到格"的位置只有场景知道
   *    （store 里只存了像素坐标，而且换屏时才更新）。按空格判"能不能坐"要用这个。
   */
  站在座位上: boolean;
  /** 玩家此刻是不是**已经坐着**（提示要显示"站起来"） */
  坐着: boolean;
  /** 玩家当前在第几格（场景回报；判"脚下是不是椅子"用） */
  玩家格: { x: number; y: number } | null;
  设站在座位上: (b: boolean, 格?: { x: number; y: number }, 坐着?: boolean) => void;
  /**
   * 请求"坐下/站起来"。
   * ⚠️ 用**计数器**而不是布尔：要的是"按下就触发一次"这个动作，不是状态。
   *    React 侧订阅它、每次变化调一次场景的 `坐下还是站起()`。
   */
  坐下请求: number;
  请求坐下: () => void;
  /** 地图上的设置弹层（Esc 打开）*/
  设置开: boolean;
  开关设置: (开?: boolean) => void;
  /** 主角在地图上的位置（换屏幕时记下来，回来还在原地，不回默认出生点）*/
  地图位置: { x: number; y: number } | null;
  记地图位置: (p: { x: number; y: number }) => void;
}

let 条目序号 = 0;
const 下个id = (): number => {
  条目序号 += 1;
  return 条目序号;
};

/** 默认间隔（G1：0.8~4 秒不等） */
const 默认间隔 = 1500;

function 间隔(节拍: 节拍): number {
  if ('间隔' in 节拍 && typeof 节拍.间隔 === 'number') return 节拍.间隔;
  return 默认间隔;
}

