/**
 * 开场与剧情的状态机。
 *
 * 设计：剧本是一条**扁平队列**，引擎每次 tick 取一条。
 *   遇到「选择」就停下等玩家点，选中后把子节拍**插到当前位置后面**，然后继续 ——
 *   所以分支不需要引擎特殊处理，播完子节拍自然汇合。
 *
 * 与游戏关卡的状态**分开存**：关卡是 Phaser 的事，剧情是 React 的事，
 * 两边通过 screen 字段分流，互不干扰。
 */
import { create } from 'zustand';
import type { 指标, 指标增减, 节拍, 说话人, 知乎卡数据 } from '../story/types';
import { 事件一, 开场镜表 } from '../story/opening';

/** 当前在哪个屏幕 */
export type 屏幕 = 'opening' | 'avg';

/** 屏幕上已经渲染出来的一条 */
export type 渲染项 =
  | { 种类: '消息'; id: number; 谁: 说话人; 文本: string; 我方: boolean }
  | { 种类: '贴纸'; id: number; 谁: 说话人; 贴纸: string; 我方: boolean }
  | { 种类: '系统'; id: number; 文本: string }
  | { 种类: '旁白'; id: number; 文本: string }
  | { 种类: '邀请'; id: number; 标题: string; 副标题: string; 按钮: string; 已接受: boolean }
  | { 种类: '知乎卡'; id: number; 卡片: 知乎卡数据 }
  | { 种类: '指标'; id: number; 变动: 指标增减 }
  | { 种类: '输入中'; id: number; 谁: 说话人 };

interface 剧情状态 {
  屏幕: 屏幕;
  /** 开场动画播到第几格 */
  开场格: number;
  开场结束: boolean;
  /** 对话队列与播放位置 */
  队列: 节拍[];
  位置: number;
  /** 已渲染的条目 */
  条目: 渲染项[];
  /** 当前等待玩家操作的东西 */
  待接受邀请: { 标题: string; 副标题: string; 按钮: string } | null;
  待选择: { 标签: string }[] | null;
  待暂停: string | null;
  指标: 指标;
  /** 对话是否播完 */
  播完: boolean;

  // 动作
  推进一步: () => void;
  接受邀请: () => void;
  选择: (序号: number) => void;
  点暂停: () => void;
  跳过开场: () => void;
  重置: () => void;
}

let 条目序号 = 0;
const 下个id = (): number => {
  条目序号 += 1;
  return 条目序号;
};

/** 默认间隔：G1 说 0.8~4 秒不等 */
const 默认间隔 = 1500;

/** 取一条节拍要停多久 */
function 间隔(节拍: 节拍): number {
  if ('间隔' in 节拍 && typeof 节拍.间隔 === 'number') return 节拍.间隔;
  return 默认间隔;
}

/** 开局状态 */
function 初始() {
  return {
    屏幕: 'opening' as 屏幕,
    开场格: 0,
    开场结束: false,
    队列: [...事件一.节拍],
    位置: 0,
    条目: [] as 渲染项[],
    待接受邀请: null,
    待选择: null,
    待暂停: null,
    指标: { 信任: 0, 协作: 0, 成长: 0 },
    播完: false,
  };
}

/** 当前这一段是不是群聊（决定气泡样式） */
function 是群聊(队列: 节拍[], 位置: number): boolean {
  // 从「邀请」之后到「暂停」之前算群聊；这里用一个简单近似：
  // 队列里出现过 邀请 且还没到周岚私聊的系统行，就算群聊
  const 已过邀请 = 队列.slice(0, 位置).some((b) => b.类型 === '邀请');
  const 已进私聊 = 队列.slice(0, 位置).some((b) => b.类型 === '系统' && b.文本.includes('周岚'));
  return 已过邀请 && !已进私聊;
}

export const useStory = create<剧情状态>((set, get) => ({
  ...初始(),

  推进一步: () => {
    const s = get();
    if (s.待选择 || s.待接受邀请 || s.待暂停) return; // 等玩家操作，不自动推进
    if (s.位置 >= s.队列.length) {
      set({ 播完: true });
      return;
    }
    const 本 = s.队列[s.位置];
    const 下个位置 = s.位置 + 1;
    const 群聊中 = 是群聊(s.队列, s.位置);

    switch (本.类型) {
      case '消息': {
        set({
          位置: 下个位置,
          条目: [
            ...s.条目,
            { 种类: '消息', id: 下个id(), 谁: 本.谁, 文本: 本.文本, 我方: 本.谁 === '刘看山' },
          ],
        });
        return;
      }
      case '贴纸': {
        set({
          位置: 下个位置,
          条目: [
            ...s.条目,
            { 种类: '贴纸', id: 下个id(), 谁: 本.谁, 贴纸: 本.贴纸, 我方: 本.谁 === '刘看山' },
          ],
        });
        return;
      }
      case '系统':
      case '旁白': {
        set({
          位置: 下个位置,
          条目: [...s.条目, { 种类: 本.类型, id: 下个id(), 文本: 本.文本 }],
        });
        return;
      }
      case '输入中': {
        // 「正在输入」是**临时**的：先插进来，2 秒后自己消失（G2：只在私聊出现）
        if (群聊中) {
          set({ 位置: 下个位置 });
          return;
        }
        const id = 下个id();
        const 快照 = get().条目;
        set({ 位置: 下个位置, 条目: [...快照, { 种类: '输入中', id, 谁: 本.谁 }] });
        setTimeout(() => {
          const 现 = get();
          set({ 条目: 现.条目.filter((x) => x.id !== id) });
        }, 1600);
        return;
      }
      case '邀请': {
        set({
          位置: 下个位置,
          待接受邀请: { 标题: 本.标题, 副标题: 本.副标题, 按钮: 本.按钮 },
        });
        return;
      }
      case '场景': {
        // 插图由组件直接读队列当前位置算，这里只推进
        set({ 位置: 下个位置 });
        return;
      }
      case '指标': {
        const 新指标 = {
          信任: s.指标.信任 + (本.变动.信任 ?? 0),
          协作: s.指标.协作 + (本.变动.协作 ?? 0),
          成长: s.指标.成长 + (本.变动.成长 ?? 0),
        };
        set({
          位置: 下个位置,
          指标: 新指标,
          条目: [...s.条目, { 种类: '指标', id: 下个id(), 变动: 本.变动 }],
        });
        return;
      }
      case '知乎卡': {
        set({
          位置: 下个位置,
          条目: [...s.条目, { 种类: '知乎卡', id: 下个id(), 卡片: 本.卡片 }],
        });
        return;
      }
      case '选择': {
        set({ 待选择: 本.选项.map((o) => ({ 标签: o.标签 })) });
        return;
      }
      case '标题': {
        set({ 位置: 下个位置 });
        return;
      }
      case '暂停': {
        set({ 位置: 下个位置, 待暂停: 本.提示 });
        return;
      }
      default: {
        set({ 位置: 下个位置 });
      }
    }
  },

  接受邀请: () => {
    const s = get();
    if (!s.待接受邀请) return;
    set({
      待接受邀请: null,
      条目: [
        ...s.条目,
        {
          种类: '邀请',
          id: 下个id(),
          标题: s.待接受邀请.标题,
          副标题: s.待接受邀请.副标题,
          按钮: s.待接受邀请.按钮,
          已接受: true,
        },
      ],
    });
  },

  选择: (序号) => {
    const s = get();
    if (!s.待选择) return;
    // 找出当前位置前面那条「选择」节拍，取它的选项
    const 选择节拍 = s.队列
      .slice(0, s.位置 + 1)
      .reverse()
      .find((b) => b.类型 === '选择');
    if (!选择节拍 || 选择节拍.类型 !== '选择') return;
    const 选中 = 选择节拍.选项[序号];
    if (!选中) return;

    // 把子节拍插到「选择」这一条的**位置**上，并把「选择」本身从队列里摘掉。
    // ⚠️ 摘掉是关键：不摘的话，播完子内容会再撞上这条「选择」→ 无限循环。
    const 插入: 节拍[] = [...选中.内容];
    if (选中.效果) 插入.push({ 类型: '指标', 变动: 选中.效果 });

    const 新队列 = [...s.队列.slice(0, s.位置), ...插入, ...s.队列.slice(s.位置 + 1)];
    set({
      队列: 新队列,
      位置: s.位置,
      待选择: null,
      条目: [
        ...s.条目,
        { 种类: '系统', id: 下个id(), 文本: `你选择了：${选中.标签}` },
      ],
    });
  },

  点暂停: () => set({ 待暂停: null, 播完: true }),

  跳过开场: () => set({ 屏幕: 'avg', 开场结束: true }),

  重置: () => {
    条目序号 = 0;
    set({ ...初始() });
  },
}));

export { 开场镜表 };
export const 剧情间隔 = 间隔;
