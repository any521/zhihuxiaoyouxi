export const useStory = create<剧情状态>((set, get) => ({
  ...初始(),

  推进一步: () => {
    const s = get();
    if (s.待选择 || s.待接受邀请 || s.待暂停) return; // 等玩家操作
    if (s.位置 >= s.队列.length) {
      set({ 播完: true });
      return;
    }
    const 本 = s.队列[s.位置];
    const 下个位置 = s.位置 + 1;

    /** 往活跃会话追加一条；玩家若正在看别的会话就记未读 */
    const 追加 = (条: 渲染项, 额外: Partial<剧情状态> = {}): void => {
      const 在看 = s.查看会话 === s.活跃会话;
      const 会话们 = s.会话们.map((c) =>
        c.id === s.活跃会话 ? { ...c, 未读: 在看 ? 0 : c.未读 + 1, 条目: [...c.条目, 条] } : c,
      );
      // 按条目类型出声
      if (条.种类 === '消息') 播放(条.我方 ? '消息发出' : '消息收到');
      else if (条.种类 === '贴纸') 播放('贴纸');
      else if (条.种类 === '邀请') 播放('群邀请');
      else if (条.种类 === '知乎卡') 播放('知乎卡');
      else if (条.种类 === '指标') {
        const 总 = (条.变动.信任 ?? 0) + (条.变动.协作 ?? 0) + (条.变动.成长 ?? 0);
        播放(总 >= 0 ? '指标上升' : '指标下降');
      }
      set({ 位置: 下个位置, 会话们, ...额外 });
    };

    switch (本.类型) {
      case '切会话': {
        const 已有 = s.会话们.some((c) => c.id === 本.id);
        const 会话们 = 已有
          ? s.会话们
          : [
              ...s.会话们,
              {
                id: 本.id,
                名字: 本.名字,
                类型: 本.会话类型,
                对方: 本.对方,
                成员: 本.成员,
                未读: 0,
                条目: [],
              },
            ];
        // ⚠️ **不自动切视图**（用户要求："改为自己点击切换会话"）。
        //    剧本只是把"消息往哪儿发"改到新会话上；玩家自己点左侧列表去看。
        //    看不到的会话会累计未读，列表上显示数字小红点。
        播放('转场', 0.3);
        set({ 位置: 下个位置, 会话们, 活跃会话: 本.id });
        return;
      }
      case '消息': {
        追加({ 种类: '消息', id: 下个id(), 谁: 本.谁, 文本: 本.文本, 我方: 本.谁 === '刘看山' });
        return;
      }
      case '贴纸': {
        追加({ 种类: '贴纸', id: 下个id(), 谁: 本.谁, 贴纸: 本.贴纸, 我方: 本.谁 === '刘看山' });
        return;
      }
      case '系统':
      case '旁白':
      case '时间': {
        追加({ 种类: 本.类型, id: 下个id(), 文本: 本.文本 });
        return;
      }
      case '输入中': {
        // 「正在输入」是临时的：先插进来，1.6 秒后自己消失（G2：只在私聊出现）
        const 当前 = s.会话们.find((c) => c.id === s.活跃会话);
        if (当前?.类型 === '群聊') {
          set({ 位置: 下个位置 });
          return;
        }
        const 新id = 下个id();
        追加({ 种类: '输入中', id: 新id, 谁: 本.谁 });
        window.setTimeout(() => {
          set((st) => ({
            会话们: st.会话们.map((c) => ({
              ...c,
              条目: c.条目.filter((x) => x.id !== 新id),
            })),
          }));
        }, 1600);
        return;
      }
      case '邀请': {
        // ⚠️ 邀请卡画在**当前这个会话**里（谁发的邀请就落在谁的私聊里），
        //    不是画进被邀请的那个群 ——
        //    实测踩过：画进群里的话，玩家在"林总私聊"里根本看不到邀请，
        //    等接受后切到群里，反而看到"群邀请卡出现在群里"，很怪。
        //    `会话id` 只用来记"接受之后该切到哪个会话"。
        const 目标 = 本.会话id ?? null;
        const 条: 渲染项 = {
          种类: '邀请',
          id: 下个id(),
          标题: 本.标题,
          副标题: 本.副标题,
          按钮: 本.按钮,
          已接受: false,
        };
        set({
          位置: 下个位置,
          会话们: s.会话们.map((c) =>
            c.id === s.活跃会话 ? { ...c, 条目: [...c.条目, 条] } : c,
          ),
          待接受邀请: { 标题: 本.标题, 副标题: 本.副标题, 按钮: 本.按钮, 会话id: 目标 },
        });
        return;
      }
      case '场景':
      case '标题': {
        set({ 位置: 下个位置 });
        return;
      }
      case '指标': {
        追加(
          { 种类: '指标', id: 下个id(), 变动: 本.变动 },
          {
            指标: {
              信任: s.指标.信任 + (本.变动.信任 ?? 0),
              协作: s.指标.协作 + (本.变动.协作 ?? 0),
              成长: s.指标.成长 + (本.变动.成长 ?? 0),
            },
          },
        );
        return;
      }
      case '知乎卡': {
        // 按主题去离线库里查真实内容（作者/摘录/链接都是真检索到的原文）。
        // 库里没有就返回「待接入」占位 —— 绝不编造来源。
        追加({ 种类: '知乎卡', id: 下个id(), 卡片: 取知乎卡(本.卡片.主题) });
        return;
      }
      case '选择': {
        set({ 待选择: 本.选项.map((o) => ({ 标签: o.标签 })) });
        return;
      }
      case '暂停': {
        set({ 位置: 下个位置, 待暂停: 本.提示 });
        return;
      }
      case '去房间': {
        // ⚠️ **只登记，不立刻切屏** —— 让玩家点一下"去 XX ▸"再切
        //    （自动推进播到这儿会停，见 Avg 的自动推进条件里的 `待去房间`）。
        //    「位置」不动：这一条下次还会被取到，玩家点了才由 `去房间()` 真正执行。
        set({ 待去房间: { 去哪: 本.去哪, 提示: 本.提示 } });
        return;
      }
      default: {
        set({ 位置: 下个位置 });
      }
    }
  },

  接受邀请: () => {
    const s = get();
    if (!s.待接受邀请) return;
    const 群 = s.待接受邀请.会话id;
    // ⚠️ **不要把邀请卡再往群里塞一张**（用户报过两次："群里多了要求去掉"）。
    //    邀请卡从始至终只存在于**发邀请的那个私聊**里；这里只是把它标成"已接受"。
    //    接受的动作 = ①把私聊里那张卡标已接受 ②如果群还不存在就建出来 ③切到群里。
    const 会话们 = s.会话们.map((c) => {
      // ① 私聊里那张卡 → 已接受
      const 条目 = c.条目.map((x) =>
        x.种类 === '邀请' && !x.已接受 ? { ...x, 已接受: true } : x,
      );
      if (c.id === 群) return { ...c, 未读: 0, 条目 };
      return 条目 === c.条目 ? c : { ...c, 条目 };
    });
    const 有群 = 群 ? 会话们.some((c) => c.id === 群) : true;
    const 最终 = 群 && !有群
      ? [
          ...会话们,
          {
            id: 群,
            名字: s.待接受邀请.标题,
            类型: '群聊' as const,
            未读: 0,
            条目: [],
          },
        ]
      : 会话们;
    set({
      待接受邀请: null,
      // 邀请是"当下正在发生的事"，点完就该看到那个群 —— 这里**故意**切视图。
      // （普通「切会话」节拍不一样：那个只改"消息往哪发"，视图不跳，玩家自己点。）
      查看会话: 群 ?? s.查看会话,
      移动端面板: '聊天',
      会话们: 最终,
    });
  },

  选择: (序号) => {
    const s = get();
    if (!s.待选择) return;
    const 选择节拍 = s.队列
      .slice(0, s.位置 + 1)
      .reverse()
      .find((b) => b.类型 === '选择');
    if (!选择节拍 || 选择节拍.类型 !== '选择') return;
    const 选中 = 选择节拍.选项[序号];
    if (!选中) return;

    // 把子节拍插到「选择」这一条的位置上，并把「选择」本身从队列里摘掉。
    // ⚠️ 摘掉是关键：不摘的话，播完子内容会再撞上这条「选择」→ 无限循环。
    const 插入: 节拍[] = [...选中.内容];

    // 玩家这一句要**立刻**显示（让"发消息"有即时反馈），所以从队列里摘掉它，
    // ⚠️ 不摘的话队列播到它时会再显示一次 —— 实测就是这样发了两遍。
    const 你选 = 选中.内容.find((b) => b.类型 === '消息' && b.谁 === '刘看山');
    if (你选) {
      const i = 插入.indexOf(你选);
      if (i >= 0) 插入.splice(i, 1);
    }

    if (选中.效果) 插入.push({ 类型: '指标', 变动: 选中.效果 });
    const 新队列 = [...s.队列.slice(0, s.位置), ...插入, ...s.队列.slice(s.位置 + 1)];

    const 新条: 渲染项[] = [{ 种类: '系统', id: 下个id(), 文本: `你选择了：${选中.标签}` }];
    if (你选 && 你选.类型 === '消息') {
      新条.push({ 种类: '消息', id: 下个id(), 谁: '刘看山', 文本: 你选.文本, 我方: true });
    }

    播放('选择确认');
    set({
      队列: 新队列,
      位置: s.位置,
      待选择: null,
      会话们: s.会话们.map((c) =>
        c.id === s.活跃会话 ? { ...c, 条目: [...c.条目, ...新条] } : c,
      ),
    });
  },

  点暂停: () => {
    const s = get();

    // 支线片段播完了：收起手机回地图，主线不动
    if (s.支线中) {
      播放('按钮');
      set({ 待暂停: null, 支线中: false, 屏幕: 'map', 附近交互点: null });
      return;
    }

    const 下一段 = 取段(s.段号 + 1);
    if (!下一段) {
      // 没有下一段了，才算整段剧情结束
      set({ 待暂停: null, 播完: true });
      return;
    }

    // 有下一段：**不直接播**，而是回地图，把指引线指向这一段的入口。
    // 这就是双模式的分工 —— 微信给信息，地图负责"去哪儿"。
    播放('转场');
    set({
      段号: s.段号 + 1,
      段标签: 段日期[s.段号 + 1] ?? '',
      队列: [],
      位置: 0,
      待暂停: null,
      播完: false,
      屏幕: 'map',
      附近交互点: null,
      地图目标: 下一段.地图入口 ?? null,
      续播: null, // 换段了，上一段的"去房间"作废
    });
  },

  /* ───────── 地图模式 ───────── */

  设附近: (id) => set({ 附近交互点: id }),

  /** 场景说"旁边现在是这个东西"（道具卡内容由 React 侧查 道具卡库） */
  设附近物: (物) => set({ 附近物: 物 }),

  /** 场景说"旁边是这位同事"（人物卡内容由 React 侧查 人物卡库） */
  设附近人: (名) => set({ 附近人: 名 }),

  /** 场景说"门口现在是开着还是关着" */
  设附近门: (门) => set({ 附近门: 门 }),

  /** 场景说"玩家脚下是不是椅子"（按空格能不能坐下要用） */
  设站在座位上: (b, 格, 坐着) =>
    set((s) => ({ 站在座位上: b, 玩家格: 格 ?? s.玩家格, 坐着: 坐着 ?? s.坐着 })),

  /**
   * 在交互点上按下交互。
   *   一、如果是下一段主线的地图入口 → 开主线（切到微信播那一段）
   *   二、否则如果这个点有支线片段 → 播支线（播完自动回地图）
   *   三、都没有 → 什么都不做（不敷衍地弹一句假话）
   */
  地图交互: (id) => {
    const s = get();
    // ⚠️ 这里要取 段号 **本身**，不是 段号+1：
    //    点暂停 已经把段号推进到"待播的那一段"，并把指引线指向了它的入口。
    //    第一次写成 段号+1，多看了下一段 → 入口对不上 → 走到点上按空格没反应。
    const 待播段 = 取段(s.段号);

    // ① 「去房间」的续播：这一段还没播完，走到目标点接着播
    //    ⚠️ 必须排在"主线入口"前面判：目标点有时**同时也是**别的东西
    //       （比如"回我的工位"，那格上还挂着交互点），先判续播才不会走岔。
    if (s.续播 && s.续播.去哪 === id) {
      播放('转场');
      set({
        屏幕: 'avg',
        位置: s.续播.从这,
        待暂停: null,
        播完: false,
        支线中: false,
        地图目标: null,
        续播: null,
        续播提示: null,
        附近交互点: null,
        搜索开: false,
      });
      return;
    }

    // ② 主线入口
    if (待播段 && 待播段.地图入口 === id) {
      播放('转场');
      set({
        屏幕: 'avg',
        队列: [...待播段.节拍],
        位置: 0,
        待暂停: null,
        播完: false,
        支线中: false,
        地图目标: null,
        续播: null,
        附近交互点: null,
        搜索开: false,
      });
      return;
    }

    // ③ 都不是？如果玩家**此刻正好站在一把椅子上**（工位/茶水间那几把），
    //    按空格就是"坐下 / 站起来"。⚠️ 只看位置，不看是哪个交互点 ——
    //    工位附近同时有 4 把椅子，按 id 判会漏。
    //    ⚠️ 必须排在"续播"和"主线入口"**后面**：那两件事优先
    //       （"回我的工位"既是续播点、又是一把椅子，得先把剧情接上）。
    const 位3 = s.玩家格;
    if (s.站在座位上 || (位3 && 座位表.some((c) => c.x === 位3.x && c.y === 位3.y))) {
      get().请求坐下();
      return;
    }
    // ④ 支线片段
    const 片段 = 地图片段表[id];
    if (片段) {
      播放('选择确认', 0.4);
      set({
        屏幕: 'avg',
        队列: [...片段],
        位置: 0,
        待暂停: null,
        支线中: true,
        附近交互点: null,
        搜索开: false,
      });
    }
  },

  回地图: () => set({ 屏幕: 'map', 附近交互点: null, 搜索开: false }),

  看人物: (谁) => set({ 看谁: 谁 }),

  /** 请求场景执行一次"坐下/站起来"（MapScreen 订阅这个计数器） */
  请求坐下: () => set((s) => ({ 坐下请求: s.坐下请求 + 1 })),

  /** 玩家点了「去 XX ▸」：现在才真的切地图、指引线指向目标、等他走过去 */
  去房间: () => {    const s = get();
    if (!s.待去房间) return;
    播放('转场');
    set({
      屏幕: 'map',
      地图目标: s.待去房间.去哪,
      // 走到目标按空格 → 从**这一条的下一条**继续（位置还停在 `去房间` 那条上）
      续播: { 去哪: s.待去房间.去哪, 从这: s.位置 + 1 },
      续播提示: s.待去房间.提示,
      待去房间: null,
      待暂停: null,
      附近交互点: null,
    });
  },

  开关设置: (开) => set((s) => ({ 设置开: 开 ?? !s.设置开 })),

  记地图位置: (p) => set({ 地图位置: p }),

  /**
   * 掏出手机（Tab / 右下角按钮 / 地图上按 Esc 之外的那个入口）。
   *
   * ⚠️⚠️ **不能只是 `屏幕='avg'`**（用户报的"主线不发消息了"就是这个）：
   *    之前如果玩家上次停在"林总私聊"（空的），掏出手机就还是看着那个空会话 ——
   *    而剧情此刻正在**群聊**里发消息 → 玩家看到的是一整屏空白，
   *    以为"剧情不发了"。实测：群里有 4 条未读，界面却停在 lin 私聊。
   * 修法：**打开时优先落到"正在发消息的那个会话（活跃会话）"**——
   *    它非空、而且有未读时，说明剧情在那边说话。
   *    （未读为 0 就尊重玩家上次看的那条，别乱跳。）
   */
  掏手机: () => {
    const s = get();
    const 活跃 = s.会话们.find((c) => c.id === s.活跃会话);
    const 该看 =
      活跃 && (活跃.未读 > 0 || 活跃.条目.length > 0) && s.查看会话 !== s.活跃会话
        ? s.活跃会话
        : s.查看会话;
    set({ 屏幕: 'avg', 搜索开: false, 查看会话: 该看 });
  },

  跳过开场: () => set({ 屏幕: 'avg' }),

  查看: (会话id) =>
    set((s) => ({
      查看会话: 会话id,
      移动端面板: '聊天',
      会话们: s.会话们.map((c) => (c.id === 会话id ? { ...c, 未读: 0 } : c)),
    })),

  回列表: () => set({ 移动端面板: '列表' }),

  /** 切左侧功能栏的面板。点"会话"就回到聊天 */
  切面板: (p) =>
    set((s) => ({
      侧栏面板: p,
      // 从别的面板切回会话时，手机端要重新落到聊天窗口
      移动端面板: p === '会话' ? s.移动端面板 : '列表',
      资料卡开: false,
    })),

  /** 个人资料卡（点功能栏里自己的头像） */
  开关资料卡: (开) => set((s) => ({ 资料卡开: 开 ?? !s.资料卡开 })),

  /** 开关搜索面板；打开时自动聚焦，关闭时清空搜索词 */
  开搜索: (开) => set({ 搜索开: 开, 搜索词: 开 ? get().搜索词 : '' }),

  设搜索词: (词) => set({ 搜索词: 词 }),

  /** 消息播放倍速，落盘 */
  设速度: (n) => {
    const 合法 = [0.5, 1, 2, 3].includes(n) ? n : 1;
    window.localStorage.setItem('lks-speed', String(合法));
    set({ 速度: 合法 });
  },

  重置: () => {
    条目序号 = 0;
    set({ ...初始() });
  },
}));

export { 开场镜表 };
