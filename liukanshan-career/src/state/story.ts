/**
 * 开场与剧情的状态机。
 *
 * 设计：剧本是一条**扁平队列**，引擎每次 tick 取一条。
 *   遇到「选择」就停下等玩家点，选中后把子节拍**插到当前位置**，并把「选择」本身摘掉 ——
 *   所以分支不需要引擎特殊处理，播完子节拍自然汇合。
 *
 * 消息按**会话**归堆（微信式）：脚本用「切会话」决定后面几条发到哪个窗口，
 * 玩家可以在左侧会话列表里点开任意一个回看历史。
 *
 * 与游戏关卡的状态**分开存**：关卡是 Phaser 的事，剧情是 React 的事。
 */
import { create } from 'zustand';
import type { 指标, 指标增减, 节拍, 说话人, 知乎卡数据 } from '../story/types';
import { 开场镜表 } from '../story/opening';
import { 段日期, 取段 } from '../story/script';
import { 地图片段表 } from '../story/mapScenes';
import { 取知乎卡 } from '../story/zhihu';
import { 播放 } from '../story/audio';

/** 当前在哪个屏幕 */
export type 屏幕 = 'opening' | 'avg' | 'map';

/** 左侧功能栏的四个面板 */
export type 侧栏面板 = '会话' | '通讯录' | '设置' | '更多';

/** 屏幕上已经渲染出来的一条 */
export type 渲染项 =
  | { 种类: '消息'; id: number; 谁: 说话人; 文本: string; 我方: boolean }
  | { 种类: '贴纸'; id: number; 谁: 说话人; 贴纸: string; 我方: boolean }
  | { 种类: '系统'; id: number; 文本: string }
  | { 种类: '旁白'; id: number; 文本: string }
  | { 种类: '邀请'; id: number; 标题: string; 副标题: string; 按钮: string; 已接受: boolean }
  | { 种类: '知乎卡'; id: number; 卡片: 知乎卡数据 }
  | { 种类: '指标'; id: number; 变动: 指标增减 }
  | { 种类: '输入中'; id: number; 谁: 说话人 };

/** 一个会话（微信左侧列表的一行 + 一个聊天窗口） */
export interface 会话 {
  id: string;
  名字: string;
  类型: '私聊' | '群聊';
  /** 私聊时的对方；群聊为空 */
  对方?: 说话人;
  /** 群聊成员，用来拼群头像 */
  成员?: 说话人[];
  未读: number;
  条目: 渲染项[];
}

interface 剧情状态 {
  屏幕: 屏幕;
  开场格: number;
  /** 当前播到第几段（对应 剧本 数组）*/
  段号: number;
  /** 当前段在会话列表顶栏显示的日期标签 */
  段标签: string;

  /** 对话队列与播放位置 */
  队列: 节拍[];
  位置: number;

  /** 会话 */
  会话们: 会话[];
  /** 脚本正在往哪个会话发消息 */
  活跃会话: string;
  /** 玩家正在看哪个会话 */
  查看会话: string;
  /** 手机端：显示列表还是聊天窗口 */
  移动端面板: '列表' | '聊天';

  /** 左侧功能栏当前选中的面板 */
  侧栏面板: 侧栏面板;
  /** 个人资料卡是否打开 */
  资料卡开: boolean;
  /** 消息播放倍速（1 = 正常） */
  速度: number;
  /** 搜索面板是否打开 */
  搜索开: boolean;
  /** 搜索词 */
  搜索词: string;

  /* ── 地图模式 ── */
  /** 玩家现在靠近哪个交互点（null = 附近没有）。场景每帧回报，React 用来显示提示。 */
  附近交互点: string | null;
  /** 指引线指向哪个交互点 */
  地图目标: string | null;
  /** 正在播地图上的支线小片段（播完「收起手机」回地图，而不是推进主线） */
  支线中: boolean;

  /** 正在看谁的人物卡（null = 没开）。点头像或点地图上的同事都会开这个。 */
  看谁: 说话人 | null;

  /** 当前等待玩家操作的东西 */
  待接受邀请: { 标题: string; 副标题: string; 按钮: string } | null;
  待选择: { 标签: string }[] | null;
  待暂停: string | null;
  指标: 指标;
  播完: boolean;

  // 动作
  推进一步: () => void;
  接受邀请: () => void;
  选择: (序号: number) => void;
  点暂停: () => void;
  跳过开场: () => void;
  查看: (会话id: string) => void;
  回列表: () => void;
  重置: () => void;
  切面板: (p: 侧栏面板) => void;
  开关资料卡: (开?: boolean) => void;
  设速度: (n: number) => void;
  开搜索: (开: boolean) => void;
  设搜索词: (词: string) => void;

  /* ── 地图模式 ── */
  /** 场景回报"附近有哪个交互点" */
  设附近: (id: string | null) => void;
  /** 走到交互点按下交互：主线入口就开主线，否则播支线片段 */
  地图交互: (id: string) => void;
  /** 从手机回地图 */
  回地图: () => void;
  /** 从地图掏手机（Esc）*/
  掏手机: () => void;
  /** 打开/关闭某个人的人物卡 */
  看人物: (谁: 说话人 | null) => void;
}

let 条目序号 = 0;
const 下个id = (): number => {
  条目序号 += 1;
  return 条目序号;
};

/** 默认间隔（G1：0.8~4 秒不等） */
const 默认间隔 = 1500;

function 间隔(节拍: 节拍): number {
  if ('间隔' in 节拍 && typeof 节拍.间隔 === 'number') return 节拍.间隔;
  return 默认间隔;
}

/** 开局：新存档，联系人里只有林总 */
function 初始() {
  return {
    屏幕: 'opening' as 屏幕,
    开场格: 0,
    段号: 0,
    段标签: 段日期[0] ?? '',
    队列: [...(取段(0)?.节拍 ?? [])] as 节拍[],
    位置: 0,
    会话们: [
      { id: 'lin', 名字: '林总', 类型: '私聊' as const, 对方: '林总' as 说话人, 未读: 0, 条目: [] },
    ] as 会话[],
    活跃会话: 'lin',
    查看会话: 'lin',
    移动端面板: '聊天' as const,
    侧栏面板: '会话' as 侧栏面板,
    资料卡开: false,
    速度: Number(window.localStorage.getItem('lks-speed')) || 1,
    搜索开: false,
    搜索词: '',
    附近交互点: null,
    地图目标: null,
    支线中: false,
    看谁: null,
    待接受邀请: null,
    待选择: null,
    待暂停: null,
    指标: { 信任: 0, 协作: 0, 成长: 0 },
    播完: false,
  };
}

export const useStory = create<剧情状态>((set, get) => ({
  ...初始(),

  推进一步: () => {
    const s = get();
    if (s.待选择 || s.待接受邀请 || s.待暂停) return; // 等玩家操作
    if (s.位置 >= s.队列.length) {
      set({ 播完: true });
      return;
    }
    const 本 = s.队列[s.位置];
    const 下个位置 = s.位置 + 1;

    /** 往活跃会话追加一条；玩家若正在看别的会话就记未读 */
    const 追加 = (条: 渲染项, 额外: Partial<剧情状态> = {}): void => {
      const 在看 = s.查看会话 === s.活跃会话;
      const 会话们 = s.会话们.map((c) =>
        c.id === s.活跃会话 ? { ...c, 未读: 在看 ? 0 : c.未读 + 1, 条目: [...c.条目, 条] } : c,
      );
      // 按条目类型出声
      if (条.种类 === '消息') 播放(条.我方 ? '消息发出' : '消息收到');
      else if (条.种类 === '贴纸') 播放('贴纸');
      else if (条.种类 === '邀请') 播放('群邀请');
      else if (条.种类 === '知乎卡') 播放('知乎卡');
      else if (条.种类 === '指标') {
        const 总 = (条.变动.信任 ?? 0) + (条.变动.协作 ?? 0) + (条.变动.成长 ?? 0);
        播放(总 >= 0 ? '指标上升' : '指标下降');
      }
      set({ 位置: 下个位置, 会话们, ...额外 });
    };

    switch (本.类型) {
      case '切会话': {
        const 已有 = s.会话们.some((c) => c.id === 本.id);
        const 会话们 = 已有
          ? s.会话们
          : [
              ...s.会话们,
              {
                id: 本.id,
                名字: 本.名字,
                类型: 本.会话类型,
                对方: 本.对方,
                成员: 本.成员,
                未读: 0,
                条目: [],
              },
            ];
        // 脚本切会话时把视图也切过去（剧情需要玩家看到）
        播放('转场', 0.3);
        set({ 位置: 下个位置, 会话们, 活跃会话: 本.id, 查看会话: 本.id, 移动端面板: '聊天' });
        return;
      }
      case '消息': {
        追加({ 种类: '消息', id: 下个id(), 谁: 本.谁, 文本: 本.文本, 我方: 本.谁 === '刘看山' });
        return;
      }
      case '贴纸': {
        追加({ 种类: '贴纸', id: 下个id(), 谁: 本.谁, 贴纸: 本.贴纸, 我方: 本.谁 === '刘看山' });
        return;
      }
      case '系统':
      case '旁白': {
        追加({ 种类: 本.类型, id: 下个id(), 文本: 本.文本 });
        return;
      }
      case '输入中': {
        // 「正在输入」是临时的：先插进来，1.6 秒后自己消失（G2：只在私聊出现）
        const 当前 = s.会话们.find((c) => c.id === s.活跃会话);
        if (当前?.类型 === '群聊') {
          set({ 位置: 下个位置 });
          return;
        }
        const 新id = 下个id();
        追加({ 种类: '输入中', id: 新id, 谁: 本.谁 });
        window.setTimeout(() => {
          set((st) => ({
            会话们: st.会话们.map((c) => ({
              ...c,
              条目: c.条目.filter((x) => x.id !== 新id),
            })),
          }));
        }, 1600);
        return;
      }
      case '邀请': {
        set({
          位置: 下个位置,
          待接受邀请: { 标题: 本.标题, 副标题: 本.副标题, 按钮: 本.按钮 },
        });
        return;
      }
      case '场景':
      case '标题': {
        set({ 位置: 下个位置 });
        return;
      }
      case '指标': {
        追加(
          { 种类: '指标', id: 下个id(), 变动: 本.变动 },
          {
            指标: {
              信任: s.指标.信任 + (本.变动.信任 ?? 0),
              协作: s.指标.协作 + (本.变动.协作 ?? 0),
              成长: s.指标.成长 + (本.变动.成长 ?? 0),
            },
          },
        );
        return;
      }
      case '知乎卡': {
        // 按主题去离线库里查真实内容（作者/摘录/链接都是真检索到的原文）。
        // 库里没有就返回「待接入」占位 —— 绝不编造来源。
        追加({ 种类: '知乎卡', id: 下个id(), 卡片: 取知乎卡(本.卡片.主题) });
        return;
      }
      case '选择': {
        set({ 待选择: 本.选项.map((o) => ({ 标签: o.标签 })) });
        return;
      }
      case '暂停': {
        set({ 位置: 下个位置, 待暂停: 本.提示 });
        return;
      }
      default: {
        set({ 位置: 下个位置 });
      }
    }
  },

  接受邀请: () => {
    const s = get();
    if (!s.待接受邀请) return;
    const 条: 渲染项 = {
      种类: '邀请',
      id: 下个id(),
      标题: s.待接受邀请.标题,
      副标题: s.待接受邀请.副标题,
      按钮: s.待接受邀请.按钮,
      已接受: true,
    };
    set({
      待接受邀请: null,
      会话们: s.会话们.map((c) => (c.id === s.活跃会话 ? { ...c, 条目: [...c.条目, 条] } : c)),
    });
  },

  选择: (序号) => {
    const s = get();
    if (!s.待选择) return;
    const 选择节拍 = s.队列
      .slice(0, s.位置 + 1)
      .reverse()
      .find((b) => b.类型 === '选择');
    if (!选择节拍 || 选择节拍.类型 !== '选择') return;
    const 选中 = 选择节拍.选项[序号];
    if (!选中) return;

    // 把子节拍插到「选择」这一条的位置上，并把「选择」本身从队列里摘掉。
    // ⚠️ 摘掉是关键：不摘的话，播完子内容会再撞上这条「选择」→ 无限循环。
    const 插入: 节拍[] = [...选中.内容];

    // 玩家这一句要**立刻**显示（让"发消息"有即时反馈），所以从队列里摘掉它，
    // ⚠️ 不摘的话队列播到它时会再显示一次 —— 实测就是这样发了两遍。
    const 你选 = 选中.内容.find((b) => b.类型 === '消息' && b.谁 === '刘看山');
    if (你选) {
      const i = 插入.indexOf(你选);
      if (i >= 0) 插入.splice(i, 1);
    }

    if (选中.效果) 插入.push({ 类型: '指标', 变动: 选中.效果 });
    const 新队列 = [...s.队列.slice(0, s.位置), ...插入, ...s.队列.slice(s.位置 + 1)];

    const 新条: 渲染项[] = [{ 种类: '系统', id: 下个id(), 文本: `你选择了：${选中.标签}` }];
    if (你选 && 你选.类型 === '消息') {
      新条.push({ 种类: '消息', id: 下个id(), 谁: '刘看山', 文本: 你选.文本, 我方: true });
    }

    播放('选择确认');
    set({
      队列: 新队列,
      位置: s.位置,
      待选择: null,
      会话们: s.会话们.map((c) =>
        c.id === s.活跃会话 ? { ...c, 条目: [...c.条目, ...新条] } : c,
      ),
    });
  },

  点暂停: () => {
    const s = get();

    // 支线片段播完了：收起手机回地图，主线不动
    if (s.支线中) {
      播放('按钮');
      set({ 待暂停: null, 支线中: false, 屏幕: 'map', 附近交互点: null });
      return;
    }

    const 下一段 = 取段(s.段号 + 1);
    if (!下一段) {
      // 没有下一段了，才算整段剧情结束
      set({ 待暂停: null, 播完: true });
      return;
    }

    // 有下一段：**不直接播**，而是回地图，把指引线指向这一段的入口。
    // 这就是双模式的分工 —— 微信给信息，地图负责"去哪儿"。
    播放('转场');
    set({
      段号: s.段号 + 1,
      段标签: 段日期[s.段号 + 1] ?? '',
      队列: [],
      位置: 0,
      待暂停: null,
      播完: false,
      屏幕: 'map',
      附近交互点: null,
      地图目标: 下一段.地图入口 ?? null,
    });
  },

  /* ───────── 地图模式 ───────── */

  设附近: (id) => set({ 附近交互点: id }),

  /**
   * 在交互点上按下交互。
   *   一、如果是下一段主线的地图入口 → 开主线（切到微信播那一段）
   *   二、否则如果这个点有支线片段 → 播支线（播完自动回地图）
   *   三、都没有 → 什么都不做（不敷衍地弹一句假话）
   */
  地图交互: (id) => {
    const s = get();
    // ⚠️ 这里要取 段号 **本身**，不是 段号+1：
    //    点暂停 已经把段号推进到"待播的那一段"，并把指引线指向了它的入口。
    //    第一次写成 段号+1，多看了下一段 → 入口对不上 → 走到点上按空格没反应。
    const 待播段 = 取段(s.段号);

    // 主线入口
    if (待播段 && 待播段.地图入口 === id) {
      播放('转场');
      set({
        屏幕: 'avg',
        队列: [...待播段.节拍],
        位置: 0,
        待暂停: null,
        播完: false,
        支线中: false,
    看谁: null,
        地图目标: null,
        附近交互点: null,
        搜索开: false,
      });
      return;
    }

    // 支线片段
    const 片段 = 地图片段表[id];
    if (片段) {
      播放('选择确认', 0.4);
      set({
        屏幕: 'avg',
        队列: [...片段],
        位置: 0,
        待暂停: null,
        支线中: true,
        附近交互点: null,
        搜索开: false,
      });
    }
  },

  回地图: () => set({ 屏幕: 'map', 附近交互点: null, 搜索开: false }),

  看人物: (谁) => set({ 看谁: 谁 }),

  掏手机: () => set({ 屏幕: 'avg', 搜索开: false }),

  跳过开场: () => set({ 屏幕: 'avg' }),

  查看: (会话id) =>
    set((s) => ({
      查看会话: 会话id,
      移动端面板: '聊天',
      会话们: s.会话们.map((c) => (c.id === 会话id ? { ...c, 未读: 0 } : c)),
    })),

  回列表: () => set({ 移动端面板: '列表' }),

  /** 切左侧功能栏的面板。点"会话"就回到聊天 */
  切面板: (p) =>
    set((s) => ({
      侧栏面板: p,
      // 从别的面板切回会话时，手机端要重新落到聊天窗口
      移动端面板: p === '会话' ? s.移动端面板 : '列表',
      资料卡开: false,
    })),

  /** 个人资料卡（点功能栏里自己的头像） */
  开关资料卡: (开) => set((s) => ({ 资料卡开: 开 ?? !s.资料卡开 })),

  /** 开关搜索面板；打开时自动聚焦，关闭时清空搜索词 */
  开搜索: (开) => set({ 搜索开: 开, 搜索词: 开 ? get().搜索词 : '' }),

  设搜索词: (词) => set({ 搜索词: 词 }),

  /** 消息播放倍速，落盘 */
  设速度: (n) => {
    const 合法 = [0.5, 1, 2, 3].includes(n) ? n : 1;
    window.localStorage.setItem('lks-speed', String(合法));
    set({ 速度: 合法 });
  },

  重置: () => {
    条目序号 = 0;
    set({ ...初始() });
  },
}));

export { 开场镜表 };
export const 剧情间隔 = 间隔;
