/**
 * 修坐姿提示词的「手」问题（零依赖）
 *
 * 问题：视角改成纯背面之后，「四格的动作」里还写着
 *   「两只黑色的手都放在身前」「左手抬起来一点点」——
 *   手在身体**前面**，从背后是看不到的。结果是生成出来
 *   头是背面、手却悬在身体两侧或前面，前后矛盾。
 *
 * 修法：把动作改成**从背后真能看见的变化**（肩膀起伏 + 身体前倾），
 * 并明确写死「手在身体前面被挡住，不要画手掌/手指/拳头」。
 *
 * 用法：node 工具/修坐姿的手.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const 根 = resolve(process.cwd());
const 文件们 = [
  join(根, '美术/提示词-10-一键复制.md'),
  join(根, '美术/提示词-10-地图重做素材.md'),
];

const 原动作 =
  '四格的动作：第一格左上，两只黑色的手都放在身前，身体直立，头略微低着。第二格右上，左手抬起来一点点，右手还在原位。第三格左下，两只手都放回身前，身体比第一格稍微前倾一点点。第四格右下，右手抬起来一点点，左手还在原位。四格之间的差别要很小很细腻，像呼吸一样的微动，不要大幅度变化。';

const 新动作 =
  '四格的动作（从背后看，**手在身体前面、被身体完全挡住**，所以只能靠肩膀和身体的细微起伏来做动画）：第一格左上，身体直立，两个肩膀齐平。第二格右上，左肩略微抬高一点点。第三格左下，身体比第一格稍微前倾一点点。第四格右下，右肩略微抬高一点点。四格之间的差别要很小很细腻，像呼吸一样的微动，不要大幅度变化。';

/** 在「视角」段后面插一段专门讲手的约束 */
const 视角锚点 = '不要画正面，也不要画四分之三侧背。';
const 手约束 =
  '\n\n背面的手：既然是从背后看，**两只手一定在身体前面、被身体挡住了**。画面里**不要画手掌、不要画手指、不要画拳头**，也不要让手臂绕到身体两侧露出来。最多只能看到肩膀下方、上臂很短的一小段后侧。';

const 原排错A =
  '排错检查：如果画面里出现腿、或者有椅子桌子，这张图就是错的。';
const 新排错A =
  '排错检查：如果画面里出现腿、或者有椅子桌子，这张图就是错的。排错检查：如果能看到手掌、手指、拳头，或者手臂从身体两侧露出来，这张图就是错的，手应该被身体挡在前面。';

let 总计 = { 动作: 0, 手约束: 0, 排错: 0 };

for (const 文件 of 文件们) {
  if (!existsSync(文件)) continue;
  let 文 = readFileSync(文件, 'utf8');
  const 前 = 文.length;

  const n1 = 文.split(原动作).length - 1;
  文 = 文.split(原动作).join(新动作);
  总计.动作 += n1;

  // 只在还没加过手约束的地方加
  if (!文.includes('背面的手：')) {
    const n2 = 文.split(视角锚点).length - 1;
    文 = 文.split(视角锚点).join(视角锚点 + 手约束);
    总计.手约束 += n2;
  }

  const n3 = 文.split(原排错A).length - 1;
  文 = 文.split(原排错A).join(新排错A);
  总计.排错 += n3;

  writeFileSync(文件, 文, 'utf8');
  console.log(`${文件.replace(根 + '\\', '')}  ${前} → ${文.length} 字符`);
}

console.log('\n=== 改手的问题 ===');
console.log(`  动作段   改了 ${总计.动作} 处`);
console.log(`  手约束   加了 ${总计.手约束} 处`);
console.log(`  排错检查 改了 ${总计.排错} 处`);
console.log('');

// 残留检查
for (const 文件 of 文件们) {
  if (!existsSync(文件)) continue;
  const 文 = readFileSync(文件, 'utf8');
  const 名 = 文件.replace(根 + '\\', '');
  const 坏 = ['手都放在身前', '左手抬起来一点点', '右手抬起来一点点'];
  const 剩 = 坏.map((k) => [k, 文.split(k).length - 1]).filter(([, n]) => n > 0);
  console.log(`  ${名}：${剩.length === 0 ? '✅ 旧写法已清干净' : '❌ ' + JSON.stringify(剩)}`);
}
