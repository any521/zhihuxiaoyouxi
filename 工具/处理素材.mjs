/* ───────── 精灵提取 ───────── */

/**
 * 从一张网格设定图里提取一组精灵。
 * 关键点：整组用**同一个缩放比例**（取组内最大包围盒算），否则帧与帧之间会跳大小。
 */
function 提取精灵组(配置) {
  const {
    源, 网格: [列数, 行数], 格子, 目标宽, 目标高, 基线y = 目标高 - 4,
    输出目录, 名字, 底部留白 = 4, 内缩 = 4,
  } = 配置;

  const img = 读取PNG(源);
  const 格宽 = Math.floor(img.width / 列数);
  const 格高 = Math.floor(img.height / 行数);

  // 1) 逐格裁边（**先抠品红再缩放**：32 色调色板里没有品红，
  //    如果先量化，品红会被量化成红色，之后就再也抠不掉了）
  const 原始 = [];
  for (const [c, r] of 格子) {
    const x0 = c * 格宽 + 内缩;
    const y0 = r * 格高 + 内缩;
    const 单元格 = 裁剪(img, x0, y0, 格宽 - 内缩 * 2, 格高 - 内缩 * 2);
    const 盒 = 内容边界(单元格);
    if (!盒) continue;
    const 内容 = 抠品红(裁剪(单元格, 盒.minX, 盒.minY, 盒.宽, 盒.高));
    原始.push({ 内容, 盒 });
  }
  if (原始.length === 0) return { 名字, 数量: 0, 输出: [] };

  // 2) 整组统一缩放：按最大的一格算比例
  const 最大宽 = Math.max(...原始.map((o) => o.内容.width));
  const 最大高 = Math.max(...原始.map((o) => o.内容.height));
  const 可用高 = 基线y - 底部留白;
  const 比例 = Math.min(目标宽 / 最大宽, 可用高 / 最大高);

  // 3) 逐格缩放 + 对齐基线 + 量化
  const 输出 = [];
  const 小图们 = [];
  for (let i = 0; i < 原始.length; i += 1) {
    const { 内容 } = 原始[i];
    const w = Math.max(1, Math.round(内容.width * 比例));
    const h = Math.max(1, Math.round(内容.height * 比例));
    const 缩放后 = 缩放到(内容, w, h);

    const 画布 = new Uint8Array(目标宽 * 目标高 * 3);
    const alpha = new Uint8Array(目标宽 * 目标高);
    const 左 = Math.floor((目标宽 - w) / 2);
    const 顶 = 基线y - h;
    for (let y = 0; y < h; y += 1) {
      for (let x = 0; x < w; x += 1) {
        const dx = 左 + x;
        const dy = 顶 + y;
        if (dx < 0 || dy < 0 || dx >= 目标宽 || dy >= 目标高) continue;
        const si = (y * w + x) * 3;
        const sa = 缩放后.alpha ? 缩放后.alpha[y * w + x] : 255;
        const di = (dy * 目标宽 + dx) * 3;
        画布[di] = 缩放后.rgb[si];
        画布[di + 1] = 缩放后.rgb[si + 1];
        画布[di + 2] = 缩放后.rgb[si + 2];
        // 硬边处理：像素画不要半透明羽化边，一律二值化
        alpha[dy * 目标宽 + dx] = sa >= 128 ? 255 : 0;
      }
    }
    let 精灵 = 去毛边({ width: 目标宽, height: 目标高, rgb: 画布, alpha });
    精灵 = 量化(精灵);
    精灵 = 加描边(精灵, [0x24, 0x1a, 0x12]); // 降采样会把原图的细描边洗掉，这里补回来
    // 抠掉量化后残留的品红
    const 抠后 = 抠品红(精灵);
    const 名 = 配置.帧名 ? 配置.帧名[i] : String(i + 1).padStart(2, '0');
    const 路径 = 成品(join(输出目录, `${名}.png`));
    写入PNG(路径, 抠后);
    输出.push(路径);
    小图们.push(抠后);
  }

  // 4) 放大预览
  const 预览倍 = 配置.预览倍 ?? Math.max(2, Math.floor(320 / 目标高));
  const 拼 = 拼图(小图们, Math.min(小图们.length, 配置.预览列数 ?? 4), 6);
  const 放大 = 最近邻放大(拼, 预览倍);
  写入PNG(成品(join(输出目录, '_预览.png')), 放大);

  return { 名字, 数量: 小图们.length, 输出, 尺寸: `${目标宽}×${目标高}` };
}

/** 整图缩放（背景类：面积平均到精确尺寸，不加 alpha） */
function 处理整图(配置) {
  const { 源, 目标: [W, H], 输出目录, 名字, 预览倍 = 1 } = 配置;
  const img = 读取PNG(源);
  const 缩放后 = 量化(缩放到(img, W, H));
  const 路径 = 成品(join(输出目录, `${名字}.png`));
  写入PNG(路径, { width: W, height: H, rgb: 缩放后.rgb });
  if (预览倍 > 1) {
    写入PNG(成品(join(输出目录, `${名字}_预览${预览倍}x.png`)), 最近邻放大(缩放后, 预览倍));
  }
  return { 名字, 数量: 1, 输出: [路径], 尺寸: `${W}×${H}` };
}

/** 切片抠图（道具/界面类：切格 → 裁边 → 缩到目标高度 → 抠透明） */
function 处理切片组(配置) {
  const {
    源, 网格: [列数, 行数], 格子, 目标高, 输出目录, 名字, 帧名, 内缩 = 4, 预览倍,
  } = 配置;
  const img = 读取PNG(源);
  const 格宽 = Math.floor(img.width / 列数);
  const 格高 = Math.floor(img.height / 行数);

  // 1) 先全部裁边，收集原始内容
  const 原始 = [];
  for (let i = 0; i < 格子.length; i += 1) {
    const [c, r] = 格子[i];
    const 单元格 = 裁剪(img, c * 格宽 + 内缩, r * 格高 + 内缩, 格宽 - 内缩 * 2, 格高 - 内缩 * 2);
    const 盒 = 内容边界(单元格);
    if (!盒) continue;
    // 先抠品红（色板里没有品红，量化后再抠就晚了）
    原始.push({ 内容: 抠品红(裁剪(单元格, 盒.minX, 盒.minY, 盒.宽, 盒.高)), 序号: i });
  }
  if (原始.length === 0) return { 名字, 数量: 0, 输出: [] };

  // 2) 整组统一比例 + 统一画布尺寸
  //    （四态按钮/图标这类必须同尺寸，否则切换状态时画面会跳一下）
  const 最大宽 = Math.max(...原始.map((o) => o.内容.width));
  const 最大高 = Math.max(...原始.map((o) => o.内容.height));
  const 比例 = 目标高 / 最大高;
  const 画布宽 = Math.max(1, Math.round(最大宽 * 比例));
  const 画布高 = 目标高;

  const 小图们 = [];
  const 输出 = [];
  for (let k = 0; k < 原始.length; k += 1) {
    const { 内容, 序号 } = 原始[k];
    const w = Math.max(1, Math.round(内容.width * 比例));
    const h = Math.max(1, Math.round(内容.height * 比例));
    const 缩放后 = 缩放到(内容, w, h);

    const rgb = new Uint8Array(画布宽 * 画布高 * 3);
    const alpha = new Uint8Array(画布宽 * 画布高);
    const 左 = Math.floor((画布宽 - w) / 2);
    const 顶 = Math.floor((画布高 - h) / 2);
    for (let y = 0; y < h; y += 1) {
      for (let x = 0; x < w; x += 1) {
        const dx = 左 + x;
        const dy = 顶 + y;
        if (dx < 0 || dy < 0 || dx >= 画布宽 || dy >= 画布高) continue;
        const si = (y * w + x) * 3;
        const di = (dy * 画布宽 + dx) * 3;
        rgb[di] = 缩放后.rgb[si];
        rgb[di + 1] = 缩放后.rgb[si + 1];
        rgb[di + 2] = 缩放后.rgb[si + 2];
        alpha[dy * 画布宽 + dx] = 缩放后.alpha ? 缩放后.alpha[y * w + x] : 255;
      }
    }
    let 成品图 = 去毛边({ width: 画布宽, height: 画布高, rgb, alpha });
    成品图 = 量化(成品图);

    const 名 = 帧名 ? 帧名[序号] : String(序号 + 1).padStart(2, '0');
    const 路径 = 成品(join(输出目录, `${名}.png`));
    写入PNG(路径, 成品图);
    输出.push(路径);
    小图们.push(成品图);
  }

  if (小图们.length > 0) {
    const 倍 = 预览倍 ?? Math.max(2, Math.floor(360 / 目标高));
    const 拼 = 拼图(小图们, Math.min(小图们.length, 4), 6);
    写入PNG(成品(join(输出目录, '_预览.png')), 最近邻放大(拼, 倍));
  }
  return { 名字, 数量: 小图们.length, 输出, 尺寸: `${画布宽}×${画布高}` };
}

/** 整图抠透明后缩放（特效/分享图这类不是规整网格的素材） */
function 处理整图抠图(配置) {
  const { 源, 输出目录, 名字, 目标宽, 预览倍 = 1 } = 配置;
  const img = 读取PNG(源);
  let 图 = 抠品红(img);
  const 盒 = 内容边界(图);
  if (盒) 图 = 裁剪(图, 盒.minX, 盒.minY, 盒.宽, 盒.高);
  const 比例 = 目标宽 / 图.width;
  图 = 缩放到(图, 目标宽, Math.max(1, Math.round(图.height * 比例)));
  图 = 去毛边(图);
  图 = 量化(图);
  图 = 抠品红(图);
  const 路径 = 成品(join(输出目录, `${名字}.png`));
  写入PNG(路径, 图);
  if (预览倍 > 1) 写入PNG(成品(join(输出目录, `${名字}_预览${预览倍}x.png`)), 最近邻放大(图, 预览倍));
  return { 名字, 数量: 1, 输出: [路径], 尺寸: `${图.width}×${图.height}` };
}

function 最近邻放大(img, 倍) {
  const W = img.width * 倍;
  const H = img.height * 倍;
  const rgb = new Uint8Array(W * H * 3);
  const alpha = img.alpha ? new Uint8Array(W * H) : null;
  for (let y = 0; y < H; y += 1) {
    for (let x = 0; x < W; x += 1) {
      const si = (Math.floor(y / 倍) * img.width + Math.floor(x / 倍)) * 3;
      const di = (y * W + x) * 3;
      rgb[di] = img.rgb[si];
      rgb[di + 1] = img.rgb[si + 1];
      rgb[di + 2] = img.rgb[si + 2];
      if (alpha) alpha[y * W + x] = img.alpha[Math.floor(y / 倍) * img.width + Math.floor(x / 倍)];
    }
  }
  return { width: W, height: H, rgb, alpha };
}

