/* ───────── 生成素材表（给游戏代码按 key 加载） ───────── */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { relative } from 'node:path';

function 收集(目录, 列表 = []) {
  for (const 名 of readdirSync(目录)) {
    if (名.startsWith('_')) continue; // _剪影测试 / _示例 这类验证产物不进素材表
    const 全路径 = join(目录, 名);
    if (statSync(全路径).isDirectory()) {
      收集(全路径, 列表);
    } else if (名.endsWith('.png') && !名.startsWith('_')) {
      列表.push(全路径);
    }
  }
  return 列表;
}

const 成品根 = 成品('');
const 文件列表 = 收集(成品根).sort();
const 素材表 = 文件列表.map((全路径) => {
  const 相对 = relative(成品根, 全路径).replace(/\\/g, '/');
  const 段 = 相对.split('/');
  const img = 读取PNG(全路径);
  return {
    key: 段.slice(1).join('/').replace(/\.png$/, ''),
    分类: 段[0],
    文件: `assets/${相对}`,
    宽: img.width,
    高: img.height,
    有透明: Boolean(img.alpha),
  };
});

writeFileSync(join(成品根, '素材表.json'), JSON.stringify(素材表, null, 2), 'utf8');
const 按分类 = new Map();
for (const 项 of 素材表) 按分类.set(项.分类, (按分类.get(项.分类) ?? 0) + 1);
console.log('\n=== 素材表 素材表.json ===');
for (const [分类, 个数] of [...按分类.entries()].sort()) {
  console.log(`  ${分类.padEnd(6)} ${String(个数).padStart(3)} 项`);
}
console.log(`  合计 ${素材表.length} 项`);
