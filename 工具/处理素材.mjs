/**
 * 素材后处理流水线（零依赖）
 *
 * 把 原图/ 里的 AI 生成图，按声明式配置表处理成 成品/ 里可直接进游戏的文件：
 *   角色 → 切片 + 裁边 + 统一缩放 + 对齐基线 + 量化 + 抠透明
 *   背景 → 面积平均缩放到精确内部分辨率（512×288 / 288×512）
 *   道具 → 切片 + 裁边 + 抠透明
 *   界面 → 切片 + 抠透明（保留细节，不缩到最小）
 * 并为每个组输出一张放大预览图，方便肉眼验收。
 *
 * 用法：node 工具/处理素材.mjs [--只处理=组名关键字]
 */
