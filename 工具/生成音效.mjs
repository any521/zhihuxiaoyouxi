/**
 * 程序合成 8-bit 音效（零依赖）
 *
 * 为什么自己做音效：
 *   一、**零版权风险** —— 抖音/素材站的音乐绝大多数有版权，抖音的授权只覆盖
 *       "在抖音平台内发视频"，不覆盖第三方游戏；参赛/商用会有麻烦。
 *   二、**风格天然匹配** —— 像素游戏的音效本来就该是方波/三角波合成的短音，
 *       网上下载的"高清音效"反而和画面不搭。
 *   三、**可精调** —— 音高、长度、包络都是参数，改一行就能重生成。
 *
 * 输出 16-bit PCM 单声道 WAV。
 * 用法：node 工具/生成音效.mjs
 */
