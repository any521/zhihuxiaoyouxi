/* ───────── 合成基元 ───────── */

/** 音名 → 频率，例如 A4=440、C5=523.25 */
const 音名频率 = (() => {
  const 表 = new Map();
  const 名 = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
  for (let 八度 = 0; 八度 <= 8; 八度 += 1) {
    for (let i = 0; i < 12; i += 1) {
      const midi = (八度 + 1) * 12 + i;
      表.set(`${名[i]}${八度}`, 440 * 2 ** ((midi - 69) / 12));
    }
  }
  return 表;
})();
const 音高 = (名) => 音名频率.get(名) ?? 440;

/** 方波（占空比可调，8-bit 的招牌音色） */
function 方波(相位, 占空 = 0.5) {
  return (相位 % 1) < 占空 ? 1 : -1;
}

/** 三角波（比方波柔和） */
function 三角波(相位) {
  const p = 相位 % 1;
  return 4 * Math.abs(p - 0.5) - 1;
}

/** 伪随机噪声（做打击感） */
function 噪声(种子) {
  let a = 种子 >>> 0;
  return () => {
    a = (a * 1664525 + 1013904223) >>> 0;
    return (a / 4294967296) * 2 - 1;
  };
}

/**
 * 一个音符。
 * @param 起 起始秒
 * @param 长 时长秒
 * @param 频 频率
 * @param 波形 '方波' | '三角'
 * @param 音量 0~1
 * @param 滑到 结束频率（做扫频，不给就不滑）
 */
function 音(缓冲, { 起, 长, 频, 波形 = '方波', 音量 = 0.35, 滑到 = null, 占空 = 0.5 }) {
  const 起样 = Math.floor(起 * 采样率);
  const 长样 = Math.floor(长 * 采样率);
  let 相位 = 0;
  for (let i = 0; i < 长样; i += 1) {
    const 位 = i / 长样;
    // 指数衰减包络 + 5ms 起音（避免爆音）
    const 包络 = Math.min(1, i / (采样率 * 0.005)) * Math.exp(-4 * 位);
    const 当前频 = 滑到 === null ? 频 : 频 + (滑到 - 频) * 位;
    相位 += 当前频 / 采样率;
    const 值 = 波形 === '三角' ? 三角波(相位) : 方波(相位, 占空);
    const 位样 = 起样 + i;
    if (位样 < 缓冲.length) 缓冲[位样] += 值 * 包络 * 音量;
  }
}

/** 一小段噪声（点击感） */
function 击(缓冲, { 起, 长, 音量 = 0.25, 种子 = 7 }) {
  const 起样 = Math.floor(起 * 采样率);
  const 长样 = Math.floor(长 * 采样率);
  const rnd = 噪声(种子);
  for (let i = 0; i < 长样; i += 1) {
    const 包络 = Math.exp(-14 * (i / 长样));
    const 位样 = 起样 + i;
    if (位样 < 缓冲.length) 缓冲[位样] += rnd() * 包络 * 音量;
  }
}

/* ───────── WAV 编码 ───────── */

function 写WAV(缓冲, 路径) {
  const 样数 = 缓冲.length;
  const 数据长 = 样数 * 2;
  const buf = Buffer.alloc(44 + 数据长);
  buf.write('RIFF', 0, 'ascii');
  buf.writeUInt32LE(36 + 数据长, 4);
  buf.write('WAVE', 8, 'ascii');
  buf.write('fmt ', 12, 'ascii');
  buf.writeUInt32LE(16, 16); // fmt 块大小
  buf.writeUInt16LE(1, 20); // PCM
  buf.writeUInt16LE(1, 22); // 单声道
  buf.writeUInt32LE(采样率, 24);
  buf.writeUInt32LE(采样率 * 2, 28); // 字节率
  buf.writeUInt16LE(2, 32); // 块对齐
  buf.writeUInt16LE(16, 34); // 位深
  buf.write('data', 36, 'ascii');
  buf.writeUInt32LE(数据长, 40);
  for (let i = 0; i < 样数; i += 1) {
    // 软削波，避免叠加后爆掉
    const v = Math.tanh(缓冲[i] * 1.1);
    buf.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(v * 30000))), 44 + i * 2);
  }
  writeFileSync(路径, buf);
  return buf.length;
}

