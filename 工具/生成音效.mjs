/**
 * 采样率。
 * ⚠️ 是 `let` 不是 `const`：**BGM 那一段会临时降到 22050**（8-bit 音色听不出差别，体积省一半），
 *    生成完再改回来。所有合成基元都是在调用时读它，所以改一处就够。
 */
