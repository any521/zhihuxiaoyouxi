/**
 * 座位体检：**`座位表` 和 `道具表` 必须对得上**。
 *
 * 为什么专门做这个检查（用户报的怪现象）：
 *   "自己工位左侧那一格**没有座位**，按空格却坐下了，人坐到外面去了"。
 *   查出来是 `座位表` 里登记了两张**根本不存在的单人沙发** `(17,4) (23,4)` ——
 *   `道具表` 里从来没摆过它们（素材也只有 `prop_ws_双人沙发`，没有单人沙发那张图）。
 *   于是人凭空"坐"在空地上。**引擎逻辑没错，是数据对不上。**
 *
 * 检查内容：
 *   一、每个座位格上**确实有一件"能坐的家具"**（椅子 / 沙发）
 *   二、每件椅子 / 沙发**都在座位表里登记了**（不然走过去坐不下 —— 反过来的漏）
 *   三、坐下时人**不会落到墙里**（座位格必须可走）
 *
 * 用法（在游戏仓库根跑）：node 工具/查座位.mjs
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const 源 = readFileSync(resolve('liukanshan-career/src/game/map/level.ts'), 'utf8');

/** 道具表：图名 + 格坐标 */
const 道具 = [];
{
  const 块 = /export const 道具表: 道具位\[\] = \[([\s\S]*?)\n\];/.exec(源)[1];
  for (const m of 块.matchAll(/\{ 图: '([^']+)', x: (\d+), y: (\d+)([^}]*)\}/g)) {
    道具.push({ 图: m[1], x: Number(m[2]), y: Number(m[3]), 尾: m[4] });
  }
}

/** 座位表：格坐标 + 家具名 */
const 座位 = [];
{
  const 块 = /export const 座位表: 座位\[\] = \[([\s\S]*?)\n\];/.exec(源)[1];
  // 展开 `[[15,4],[18,4]].map(...)` 那种
  const 展开 = /\[([\s\S]*?)\]\.map\(\(\[x, y\]\) => \(\{([^}]*)\}\)\)/.exec(块);
  if (展开) {
    for (const m of 展开[1].matchAll(/\[(\d+),\s*(\d+)\]/g)) {
      座位.push({ x: Number(m[1]), y: Number(m[2]), 家具: '转椅' });
    }
  }
  for (const m of 块.matchAll(/\{ x: (\d+), y: (\d+), 家具: '([^']+)'/g)) {
    // 跳过 `.map` 里那段（已经被上面展开过了）
    if (展开 && 展开.index !== undefined) {
      const 该行 = 块.slice(0, m.index).split('\n').length;
      const 展开行 = 块.slice(0, 展开.index).split('\n').length;
      const 展开结束行 = 块.slice(0, (展开.index ?? 0) + 展开[0].length).split('\n').length;
      if (该行 >= 展开行 && 该行 <= 展开结束行) continue;
    }
    座位.push({ x: Number(m[1]), y: Number(m[2]), 家具: m[3] });
  }
}

/** 占地表：图名 → [宽, 高]（用来算家具横跨哪几格） */
const 占地表 = {};
{
  const 块 = /export const 占地表: Record<string, \[number, number\]> = \{([\s\S]*?)\n\};/.exec(源)[1];
  for (const m of 块.matchAll(/^\s*([A-Za-z_][\w\u4e00-\u9fa5]*):\s*\[(\d+),\s*(\d+)\]/gm)) {
    占地表[m[1]] = [Number(m[2]), Number(m[3])];
  }
}

/** 哪些图是"能坐的家具"（按文件名判） */
const 能坐的图 = (图) => /转椅|沙发|会议椅/.test(图);
const 家具们 = 道具.filter((p) => 能坐的图(p.图));

/**
 * 这件家具**横跨**哪几格（含它占地的宽度）。
 *
 * ⚠️ 为什么要算"横跨"而不是只比中心格：双人沙发宽 44px ≈ 1.4 格，
 *    摆中心在 (30,20) 时会**压到 (31,20)** 一格；那张"半个沙发"也是能坐的，
 *    所以座位表里登记 (31,20) 是**对的**，不能当成"空地上凭空有座位"（第一版就误报了）。
 */
function 横跨(件) {
  const [宽] = 占地表[件.图] ?? [32, 32];
  const 中心 = 件.x * 32 + 16;
  const 左 = Math.floor((中心 - 宽 / 2) / 32);
  const 右 = Math.floor((中心 + 宽 / 2 - 1) / 32);
  const 列 = [];
  for (let x = 左; x <= 右; x += 1) 列.push(x);
  return { 行: 件.y, 列 };
}
/** 这个座位格是不是落在这件家具的占地里 */
const 压在这件家具上 = (件, x, y) => y === 件.y && 横跨(件).列.includes(x);

console.log(`道具表里"能坐的家具" ${家具们.length} 件；座位表登记了 ${座位.length} 个座位\n`);

let 坏 = 0;
const 报 = (ok, 说明) => {
  console.log(`  ${ok ? '✓' : '✗'} ${说明}`);
  if (!ok) 坏 += 1;
};

/* ① 每个座位格上要真有家具（按占地判定，不要求格坐标完全相等） */
console.log('=== ① 座位表里的每一格，都得压在"能坐的家具"上 ===');
for (const 座 of 座位) {
  const 有 = 家具们.find((p) => 压在这件家具上(p, 座.x, 座.y));
  报(
    !!有,
    `座位 (${座.x},${座.y}) ${座.家具} ${有 ? `← 压在 ${有.图}(${有.x},${有.y}) 上` : '❌ **那里没有任何能坐的家具**（人会坐到空地上）'}`,
  );
}

/* ② 每件椅子/沙发至少要有一个座位登记（不然走过去坐不下） */
console.log('\n=== ② 每件椅子 / 沙发都至少登记了一个座位 ===');
for (const p of 家具们) {
  const 有 = 座位.some((s) => 压在这件家具上(p, s.x, s.y));
  报(!!有, `${p.图} (${p.x},${p.y}) ${有 ? '' : '❌ **一个座位都没登记**（走过去按空格坐不下）'}`);
}

console.log(`\n结论：${坏 ? `❌ ${坏} 处对不上（座位表和道具表必须一一对应）` : '✅ 座位表与道具表完全对得上'}`);
process.exit(坏 ? 1 : 0);
